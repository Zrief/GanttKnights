def test_资源板块顺序与标点不应改变事件集合(样本, 模块):
    公告, api, _ = 模块
    原文 = 样本("矢量突破03")
    def 生成(文本, 倒序=False):
        表 = 公告.抽板块(文本, datetime(2026, 10, 1))
        if 倒序:
            表.reverse()
        输出 = api.认领与生成([], {"矢量突破/03/活动公告": 表})
        # 比较时间与数量，不要求不同标点的展示名完全一致。
        return sorted((e["类型"], e["开始时间"], e["结束时间"]) for e in 输出)
    基准 = 生成(原文)
    assert 基准 == 生成(原文, True), "认领→生成层依赖板块顺序"
    assert 基准 == 生成(原文.replace("“资源收集”", "「资源收集」")), "命名标点改变去留"


