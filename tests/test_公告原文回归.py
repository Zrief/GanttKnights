    表 = 公告.抽板块(样本("庆典2026"), datetime(2026, 11, 1))
    输出 = 汇总.去重排序(api.认领与生成([], {庆典页: 表}))
    按名 = {e["名称"]: e["类型"] for e in 输出}
    assert 按名["感谢庆典2026 限时签到"] == 2
    assert 按名["感谢庆典2026 特别招募活动·预选"] == 2    # 特别招募＝福利（2026-10-31 定）
    assert 按名["感谢庆典2026 特别招募活动·招募"] == 2
    # 老三样整类跳过（2026-10-31）：不再生成
    assert not any(片段 in 名称 for 名称 in 按名 for 片段 in ("特别登录", "每日赠送", "许愿墙"))
    资源表 = 公告.抽板块(样本("矢量突破03"), datetime(2026, 10, 1))
    资源输出 = api.认领与生成([], {"矢量突破/03/活动公告": 资源表})
    assert sum(e["名称"] == "资源收集全天开放" for e in 资源输出) == 1


