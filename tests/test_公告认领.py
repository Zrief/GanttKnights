def 成员(名: str, **覆盖) -> dict:
    基础 = {
        "事件名": 名, "显示名": 名,
        "开始": "2026-09-04 12:00:00", "结束": "2026-09-18 03:59:00",
        "类型": 1, "已结束": False, "公告页": None, "锚点": None,
    }
    基础.update(覆盖)
    return 基础


# ---------- 活动页模板 ----------

def test_解析活动信息与公告定位(公告):
    信息 = 公告.解析活动信息(此夜同行页)
    assert 信息["公告"] == "月行水上/活动公告#【明日方舟 × 女神异闻录３ Reload】，签到活动开启"
    assert 公告.公告定位(信息["公告"]) == (
        "月行水上/活动公告", "【明日方舟 × 女神异闻录３ Reload】，签到活动开启",
    )
    assert 公告.解析活动信息("没有模板的页面") == {}
    assert 公告.公告定位("逐影集趣/活动公告") == ("逐影集趣/活动公告", "")


# ---------- 板块表 ----------

def test_抽板块_跳过寻访与关卡段(公告):
    板块们 = 公告.抽板块(月行水上公告, 参考)
    标题们 = [b.标题 for b in 板块们]
    assert len(板块们) == 2                       # 寻访板块被跳过（条目另有来源）
    assert not any("寻访" in t for t in 标题们)
    主体 = next(b for b in 板块们 if b.是主体)
    assert 主体.窗口 == ("2026-09-04 12:00:00", "2026-09-25 03:59:00")
    assert 主体.关卡各段 == [("2026-09-04 12:00:00", "2026-09-18 03:59:00")]


def test_板块条目_无人认领的命名(公告):
    条目们 = {e["名称"]: e for e in (
        条目 for b in 公告.抽板块(逐影集趣公告, 参考)
        for 条目 in 公告.板块条目(b, "逐影集趣")
    )}
    assert "逐影集趣 签到" in 条目们              # 签到板块的泛名兜底
    assert "逐影集趣 组合包" in 条目们
    assert "【剿灭作战】默祷圣祠" in 条目们        # 长期板块：【官方名】+对象名
    assert 条目们["【剿灭作战】默祷圣祠"]["类型"] == 99
    assert "新装" not in "".join(条目们)          # 时装板块被跳过


# ---------- 认领与生成 ----------

def 月行页们(公告) -> dict:
    return {"月行水上/活动公告": 公告.抽板块(月行水上公告, 参考)}


def 逐影页们(公告) -> dict:
    return {"逐影集趣/活动公告": 公告.抽板块(逐影集趣公告, 参考)}


def test_锚点认领_板块名与活动名无关(公告, api):
    """此夜同行的板块叫「【…】签到活动开启」——标题永远配不上，只有锚点能救。"""
    成员们 = [
        成员("月行水上", 公告页="月行水上/活动公告"),
        成员("此夜同行", 类型=2, 公告页="月行水上/活动公告",
             锚点="【明日方舟 × 女神异闻录３ Reload】，签到活动开启"),
    ]
    条目们 = {e["名称"]: e for e in api.认领与生成(成员们, 月行页们(公告))}
    # 签到板块被认领 → 条目叫 此夜同行，且不再自生成「月行水上 签到」
    assert 条目们["此夜同行"]["开始时间"] == "2026-09-04 12:00:00"
    assert 条目们["此夜同行"]["结束时间"] == "2026-09-18 03:59:00"
    assert "月行水上 签到" not in 条目们
    # 主体的 ◆ 段照常生成 关卡 条目
    assert 条目们["月行水上 关卡"]["结束时间"] == "2026-09-18 03:59:00"


def test_标题认领_公告时间胜过抄错的ask窗口(公告, api):
    """稳态测定案例：ask 窗口被抄成月行水上那批的，公告板块才是对的。"""
    成员们 = [成员("稳态测定", 类型=2, 公告页="逐影集趣/活动公告")]
