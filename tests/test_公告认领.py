def test_锚点认领_板块名与活动名无关(公告, api):
    """此夜同行的板块叫「【…】签到活动开启」——标题永远配不上，只有锚点能救。"""
    成员们 = [
        成员("月行水上", 公告页="月行水上/活动公告"),
        成员("此夜同行", 类型=2, 公告页="月行水上/活动公告",
             锚点="【明日方舟 × 女神异闻录３ Reload】，签到活动开启"),
    ]
    条目们 = {e["名称"]: e for e in api.认领与生成(成员们, 月行页们(公告))}
    # 签到板块被认领 → 条目叫 此夜同行，且不再自生成「月行水上 签到」
    assert 条目们["此夜同行"]["开始时间"] == "2026-09-04 12:00:00"
    assert 条目们["此夜同行"]["结束时间"] == "2026-09-18 03:59:00"
    assert "月行水上 签到" not in 条目们
    # 主体的 ◆ 段照常生成 关卡 条目
    assert 条目们["月行水上 关卡"]["结束时间"] == "2026-09-18 03:59:00"


