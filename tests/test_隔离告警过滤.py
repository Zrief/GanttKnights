"""已结束公告页的隔离不报"部分活动未更新"（2026-10-31 定）。

初始化会回溯半年，扫到早已结束的老公告；解析失败只记 debug，不算"这次没更新"。
公告页父活动仍在进行时才该警告。
"""
from __future__ import annotations


def 板块(内核模块, 页标题='某活动', 窗口=None):
    return 内核模块('解析_公告').板块(标题=f'2026「{页标题}」，「某板块」活动开启',
                               窗口=窗口, 关卡各段=[], 类型=1, 是主体=False)


def 成员(**覆盖):
    m = dict(事件名='某活动', 显示名='某活动', 公告页='某活动/活动公告', 锚点=None,
             类型=1, 开始='2099-01-01 00:00:00', 结束='2099-12-31 23:59:00', 已结束=False)
    m.update(覆盖)
    return m


def test_已结束公告页的隔离不进入更新问题(内核模块):
    api = 内核模块('解析_API活动')
    m = 成员(已结束=True)
    batch = api.认领与生成([m], {'某活动/活动公告': [板块(内核模块)]})
    assert batch == []                      # 依旧不生成（不伪造时间）
    assert batch.隔离来源                  # 来源仍被标记（写盘时不覆盖旧行）
    assert not batch.更新问题               # 但不给用户看


def test_进行中公告页的隔离仍要警告(内核模块):
    api = 内核模块('解析_API活动')
    m = 成员(已结束=False)
    batch = api.认领与生成([m], {'某活动/活动公告': [板块(内核模块)]})
    assert batch == []
    assert any('已局部隔离' in q for q in batch.更新问题)
