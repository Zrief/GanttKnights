"""甘特行规则（两条，纯函数、不依赖 matplotlib）：

1. **铺满全图的常驻条并成一行**，快结束的单独起行（2026-09-24 定）。
2. **同一活动的多时段并成一行**（2026-10-31 定）：按显式 `活动关联` 分组，
   不从名称或日期猜；没有关联的旧数据仍走逐条/常驻逻辑。
"""

from __future__ import annotations

from datetime import datetime

from src.活动 import 活动
from src.甘特行 import 分行, 铺满全图

左 = datetime(2026, 9, 24)
右 = datetime(2026, 10, 12)

关联 = '["公告活动关联-v1","页","块"]'


def 阶段(名: str, 起: str, 止: str, 角色: str, 序号: int = 0) -> 活动:
    return 活动(名, datetime.fromisoformat(起), datetime.fromisoformat(止), 1,
              活动关联=关联, 活动本名='活动甲', 时间角色=角色, 阶段序号=序号)


def 常驻(名: str, 止: datetime = datetime(2027, 5, 15)) -> 活动:
    return 活动(名, datetime(2026, 5, 15), 止, 99)


def test_铺满全图() -> None:
    assert 铺满全图(常驻("甲"), 左, 右)
    # 结束时刻在窗口**之外**（看不见右端）→ 照样算常驻，仍然并
    assert 铺满全图(常驻("甲", datetime(2026, 10, 26)), 左, 右)
    # 右端落进窗口 → 图上看得见它要结束了 → 不再并
    assert not 铺满全图(常驻("甲", datetime(2026, 10, 5)), 左, 右)


def test_相邻的常驻条并成一行() -> None:
    行们 = 分行([常驻("甲"), 常驻("乙"), 常驻("丙")], 左, 右)
    assert [len(行) for 行 in 行们] == [3]
    assert [e.名称 for e in 行们[0]] == ["甲", "乙", "丙"]


def test_快结束的单独起一行() -> None:
    行们 = 分行([常驻("甲"), 常驻("快结束", datetime(2026, 10, 5)), 常驻("丙")], 左, 右)
    assert [len(行) for 行 in 行们] == [1, 1, 1]
    assert [行[0].名称 for 行 in 行们] == ["甲", "快结束", "丙"]


def test_普通条各自一行() -> None:
    行们 = 分行([
        活动("活动甲", datetime(2026, 9, 25), datetime(2026, 10, 5), 1),
        活动("活动乙", datetime(2026, 9, 26), datetime(2026, 10, 6), 1),
    ], 左, 右)
    assert [len(行) for 行 in 行们] == [1, 1]


def test_混合顺序保持() -> None:
    """铺满的两条并一行、快结束的另起一行、普通条各自一行 —— 自上而下的次序不变。"""
    行们 = 分行([
        常驻("甲"), 常驻("乙"), 常驻("丙", datetime(2026, 10, 4)),
        活动("活动甲", datetime(2026, 9, 25), datetime(2026, 10, 5), 1),
    ], 左, 右)
    assert [len(行) for 行 in 行们] == [2, 1, 1]
    assert [行[0].名称 for 行 in 行们] == ["甲", "丙", "活动甲"]


def test_同一活动的多时段并成一行() -> None:
    """第二条规则：按显式活动关联分组，组内次序按输入顺序，不与相邻条目混行。"""
    组 = [阶段("活动甲·一阶段", "2026-09-25 12:00:00", "2026-10-05 03:59:00", "关卡开放", 1),
          阶段("活动甲·二阶段", "2026-10-01 16:00:00", "2026-10-05 03:59:00", "关卡开放", 2),
          阶段("活动甲·商店", "2026-09-25 12:00:00", "2026-10-08 03:59:00", "兑换开放")]
    普通 = 活动("活动乙", datetime(2026, 9, 26), datetime(2026, 10, 6), 1)
    行们 = 分行([普通, *组], 左, 右)
    assert [len(行) for 行 in 行们] == [1, 3]
    assert [e.名称 for e in 行们[1]] == [f"活动甲·{x}" for x in ("一阶段", "二阶段", "商店")]


def test_无关联或本名不一致不并成全时段行() -> None:
    """没有显式关联、或本名不同时，宁可逐条排，也不按名字猜成同一个活动。"""
    无关联 = 活动("活动丙·一阶段", datetime(2026, 9, 25), datetime(2026, 10, 5), 1)
    另一本名 = 活动("活动甲·旧写法", datetime(2026, 9, 26), datetime(2026, 10, 5), 1,
                活动关联=关联, 活动本名="另一个活动", 时间角色="关卡开放", 阶段序号=1)
    行们 = 分行([无关联, 另一本名], 左, 右)
    assert [len(行) for 行 in 行们] == [1, 1]
