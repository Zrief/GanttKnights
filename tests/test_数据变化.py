"""数据日差：由合并动作直接产出（`新增 / 改动 / 过期清理`）+ 落盘记录。

流程：初始化一次拿全量，之后每天抓取 → 合并（有新增就加、过期就删）→ 出一张图。
日差就是合并动作的副产品，不需要"事后拿两份数据对比"。
"""

from __future__ import annotations

import json
from datetime import datetime

import pytest


@pytest.fixture(scope="module")
def 汇总(内核模块):
    return 内核模块("汇总_活动")


@pytest.fixture(scope="module")
def 变化模块(内核模块):
    return 内核模块("数据变化")


def 活动(名, 结束, 开始="2026-09-01 04:00:00", 类型=1, 来源=""):
    return {"名称": 名, "开始时间": 开始, "结束时间": 结束, "类型": 类型, "_parent": 来源}


现在 = "2026-09-14 10:00:00"


def test_首次建立不报新增(tmp_path, 汇总):
    差 = 汇总.合并保存CSV([活动("甲", "2026-09-20 03:59:00")], tmp_path / "d.csv", 现在)
    assert 差.首次 and 差.原有条数 == 0
    assert 差.新增 == () and 差.改动 == () and not 差.有变化


def test_新增_改动_与_过期清理(tmp_path, 汇总):
    csv = tmp_path / "d.csv"
    汇总.合并保存CSV([活动("甲", "2026-09-20 03:59:00"),
                     活动("乙", "2026-09-30 03:59:00")], csv, 现在)
    差 = 汇总.合并保存CSV([
        活动("甲", "2026-09-20 03:59:00"),                      # 没变
        活动("乙", "2026-09-28 03:59:00"),                      # 时间改了
        活动("丙", "2026-09-25 03:59:00"),                      # 新的
        活动("早就结束了", "2026-08-01 03:59:00"),              # 进来就该被清掉
    ], csv, 现在)
    assert 差.新增 == ("丙",)          # 立刻过期的那个不算新增（卡池一览每天带回几十条这种）
    assert 差.改动 == ("乙",)
    assert 差.过期清理 == 0


def test_原本存在的条目过期计入过期清理(tmp_path, 汇总):
    csv = tmp_path / "d.csv"
    汇总.合并保存CSV([活动("甲", "2026-09-20 03:59:00"),
                     活动("乙", "2026-09-20 03:59:00"),
                     活动("丙", "2026-09-20 03:59:00")], csv, 现在)
    # 甲 被改到过去 → 会被清理线删掉；乙丙留着（数据保护也不允许 3→0 的清空）
    差 = 汇总.合并保存CSV([活动("甲", "2026-08-01 03:59:00"),
                         活动("乙", "2026-09-20 03:59:00"),
                         活动("丙", "2026-09-20 03:59:00")], csv, 现在)
    assert 差.过期清理 == 1


def 长期(名, 结束="2027-05-15 03:59:00"):
    return 活动(名, 结束, 开始="2026-05-15 16:00:00", 类型=99)


def test_长期条目改名前后合并成一条(tmp_path, 汇总):
    """长期的前缀换过写法（裸名/【剿灭】/【剿灭作战】），身份键要认出是同一条：
    旧行被新行顶掉，而不是永久并存（2026-09-24 线上实测 默祷圣祠×2 / 重启锚点×2）"""
    csv = tmp_path / "d.csv"
    汇总.合并保存CSV([长期("重启锚点"), 长期("【剿灭】默祷圣祠", "2026-10-26 03:59:00")], csv, 现在)
    汇总.合并保存CSV([长期("【生息演算】重启锚点"),
                     长期("【剿灭作战】默祷圣祠", "2026-10-26 03:59:00")], csv, 现在)
    import csv as _csv
    with open(csv, encoding="utf-8-sig") as f:
        名们 = [r["名称"] for r in _csv.DictReader(f)]
    assert sorted(名们) == ["【剿灭作战】默祷圣祠", "【生息演算】重启锚点"]


def test_去重排序认出长期前缀变体(汇总):
    条目 = 汇总.去重排序([长期("【剿灭】默祷圣祠"), 长期("【剿灭作战】默祷圣祠")])
    assert len(条目) == 1


def test_记录按天冻结_文本可读(tmp_path, 汇总, 变化模块):
    路径 = 变化模块.默认路径(tmp_path)
    差 = 汇总.合并差异(新增=("甲", "乙", "丙", "丁", "戊", "己"), 改动=("庚",), 过期清理=3, 原有条数=9)
    记录 = 变化模块.记下并取(路径, 差, "2026-09-14")
    assert 记录.日期 == "2026-09-14" and 记录.对比日期 == ""
    # 同一天第二次合并不改写（保证早上推的和晚上看的是同一份）
    assert 变化模块.记下并取(路径, 汇总.合并差异(新增=("新东西",)), "2026-09-14").新增 == 记录.新增
    # 换一天改写，且对比日期取上一次的日期
    隔天 = 变化模块.记下并取(路径, 汇总.合并差异(), "2026-09-15")
    assert 隔天.对比日期 == "2026-09-14"
    文本 = 记录.文本()
    assert "本次" in 文本 and "🆕 甲、乙、丙 等 6 个" in 文本
    assert "✏️ 庚" in 文本 and "🧹 清理 3" in 文本
    assert "｜" in 文本, "段间用竖线，别再写成'；'那种长句"


def test_没有变化与首次都没有文本(变化模块):
    assert 变化模块.数据变化(日期="x").文本() == ""
    assert 变化模块.数据变化(日期="x", 新增=("甲",), 首次=True).文本() == ""


def test_读记录容错(tmp_path, 变化模块):
    路径 = tmp_path / "r.json"
    路径.write_text("{ 坏 json", encoding="utf-8")
    assert 变化模块.读(路径) is None
    路径.write_text("[]", encoding="utf-8")
    assert 变化模块.读(路径) is None
    路径.write_text(json.dumps({"日期": "2026-09-14", "新增": "不是列表", "过期清理": "坏"}),
                    encoding="utf-8")
    坏 = 变化模块.读(路径, "2026-09-14")
    assert 坏 is not None and 坏.新增 == () and 坏.过期清理 == 0
    assert 变化模块.读(路径, "2026-01-01") is None
    assert not list(tmp_path.glob(".变化-*.tmp"))     # 原子写不留残渣
