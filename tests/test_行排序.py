"""甘特行排序：组间次序固定，组内按“整行最晚结束”升序（2026-10-31 定）。"""
from __future__ import annotations

from datetime import datetime

from src.活动 import 活动
from src.甘特行 import 分行
from src.绘图_排版 import 行们排序

左 = datetime(2026, 10, 24)
右 = datetime(2026, 12, 3)
关联 = '["公告活动关联-v1","页","块"]'


def 条(名, 起, 止, *, 类型=1, 子类型='', 关联值='', 角色='', 序号=0, 本名=None):
    return 活动(名, datetime.fromisoformat(起), datetime.fromisoformat(止), 类型,
              子类型=子类型, 活动关联=关联值,
              活动本名=(本名 if 本名 is not None else (名 if 关联值 else '')),
              时间角色=角色, 阶段序号=序号)


def test_组内按最晚结束升序():
    记录 = [条('福利晚', '2026-11-01 12:00:00', '2026-11-20 03:59:00', 类型=2),
            条('福利早', '2026-11-01 12:00:00', '2026-11-05 03:59:00', 类型=2),
            条('福利中', '2026-10-25 12:00:00', '2026-11-10 03:59:00', 类型=2)]
    行们 = 行们排序(分行(list(reversed(记录)), 左, 右))
    assert [行[0].名称 for 行 in 行们] == ['福利早', '福利中', '福利晚']


def test_多时段行按组内最晚结束归位():
    """特别招募 10-24 就开始，但 12-02 才结束——不能因为它“开始最早”排到组首。"""
    组 = [条('招募·预选', '2026-10-24 21:30:00', '2026-11-01 06:59:00', 类型=2,
             关联值=关联, 角色='流程阶段', 本名='招募'),
          条('招募·招募', '2026-11-01 12:00:00', '2026-12-02 03:59:00', 类型=2,
             关联值=关联, 角色='流程阶段', 本名='招募')]
    早签 = 条('前瞻签到', '2026-10-24 21:30:00', '2026-11-03 03:59:00', 类型=2)
    晚签 = 条('补给签到', '2026-11-12 04:00:00', '2026-11-22 03:59:00', 类型=2)
    行们 = 行们排序(分行(list(reversed([*组, 早签, 晚签])), 左, 右))
    assert len(行们) == 3                                  # 两条招募仍并成一行
    assert 行们[0][0].名称 == '前瞻签到' and 行们[1][0].名称 == '补给签到'
    末行 = 行们[-1]
    assert {t.名称 for t in 末行} == {'招募·预选', '招募·招募'}, '招募整行按 12-02 排到组末'


def test_同结束时按开始时间再按Unicode名称():
    """名称排序按码位（确定性优先），不按拼音。"""
    记录 = [条('乙', '2026-11-02 12:00:00', '2026-11-10 03:59:00', 类型=2),
            条('甲', '2026-11-02 12:00:00', '2026-11-10 03:59:00', 类型=2),
            条('更早开始', '2026-11-01 12:00:00', '2026-11-10 03:59:00', 类型=2)]
    行们 = 行们排序(分行(list(reversed(记录)), 左, 右))
    assert [行[0].名称 for 行 in 行们] == ['更早开始', '乙', '甲']   # 乙 U+4E59 < 甲 U+7532


def test_甄选并入限时分组():
    """左列归类：中坚甄选与限时同组（数据里的子类型仍是「甄选」）。"""
    from src.绘图_排版 import 组标签
    甄选池 = 条('【中坚池】中坚甄选 · 甲 / 乙', '2026-11-12 04:00:00',
                '2026-11-26 03:59:00', 类型=0, 子类型='甄选')
    限时池 = 条('【寻访】某池 · 丙', '2026-11-05 12:00:00',
                '2026-11-19 03:59:00', 类型=0, 子类型='限时')
    assert 组标签(甄选池) == '限时'
    行们 = 行们排序(分行(list(reversed([甄选池, 限时池])), 左, 右))
    assert [行[0].名称 for 行 in 行们] == ['【寻访】某池 · 丙', '【中坚池】中坚甄选 · 甲 / 乙']
    assert len({组标签(行[0]) for 行 in 行们}) == 1


def test_组间次序不因结束时间改变():
    记录 = [条('福利先结束', '2026-11-01 12:00:00', '2026-11-02 03:59:00', 类型=2),
            条('活动后结束', '2026-11-01 12:00:00', '2026-12-01 03:59:00', 类型=1),
            条('长期最早', '2026-05-15 16:00:00', '2026-11-03 03:59:00', 类型=99)]
    行们 = 行们排序(分行(list(reversed(记录)), 左, 右))
    assert [行[0].类型 for 行 in 行们] == [1, 2, 99]   # 活动 → 福利 → 长期
