"""公告时间解析：年份推断（2026-09-14 修的那个 bug）。

公告里多数只写"X月X日"，年份要靠**父活动的时间窗**推断——用"今天"当基准会把
2025 年的老公告算成今年，生成一批"未来活动"永久留在库里。
"""

from __future__ import annotations

from datetime import datetime

import pytest


@pytest.fixture(scope="module")
def 解析时间(内核模块):
    return 内核模块("解析_公告").解析时间


@pytest.mark.parametrize("文本,参考,期望", [
    # 揭幕者们2025：活动 2025-11-25 起
    ("活动时间：11月25日 16:00 - 12月09日 03:59", datetime(2025, 11, 25),
     ("2025-11-25 16:00:00", "2025-12-09 03:59:00")),
    # 出苍白海2025：跨年，结束年份在公告里写明了
    ("活动时间：12月19日 04:00 - 2026年01月02日 03:59", datetime(2025, 12, 26),
     ("2025-12-19 04:00:00", "2026-01-02 03:59:00")),
    ("活动时间：12月05日 12:00 - 12月26日 03:59", datetime(2025, 12, 15),
     ("2025-12-05 12:00:00", "2025-12-26 03:59:00")),
    # 红丝绒2026：正常年份
    ("活动时间：07月20日 04:00 - 08月03日 03:59", datetime(2026, 7, 25),
     ("2026-07-20 04:00:00", "2026-08-03 03:59:00")),
    # 跨年公告（12月 → 次年1月）：结束早于开始 → 结束年 +1
    ("活动时间：12月31日 04:00 - 01月14日 03:59", datetime(2026, 1, 5),
     ("2025-12-31 04:00:00", "2026-01-14 03:59:00")),
])
def test_年份按父活动时间窗推断(解析时间, 文本, 参考, 期望):
    assert 解析时间(文本, 参考) == 期望


def test_关卡行也认(解析时间):
    assert 解析时间("◆「演出开始」&「为戏剧，为永恒」：07月20日 04:00 - 07月30日 03:59",
                  datetime(2026, 7, 25)) == ("2026-07-20 04:00:00", "2026-07-30 03:59:00")


def test_显式年份优先(解析时间):
    assert 解析时间("活动时间：12月19日 04:00 - 2026年01月02日 03:59",
                  datetime(2025, 12, 26)) == ("2025-12-19 04:00:00", "2026-01-02 03:59:00")


def test_没有参考时退回今天(解析时间):
    """兜底行为（公告解析一律传参考，这条只是保证不抛异常）。"""
    assert 解析时间("活动时间：12月31日 04:00 - 01月14日 03:59") is not None


def test_解析不出来给_None(解析时间):
    assert 解析时间("没有时间的一句话", datetime(2026, 1, 1)) is None
