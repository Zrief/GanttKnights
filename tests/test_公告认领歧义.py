"""认领顺序无关契约：仅内存板块/成员，离线、不生成缓存或 CSV。"""
from __future__ import annotations

from copy import deepcopy
from datetime import datetime
from itertools import permutations

import pytest


@pytest.fixture(scope='module')
def 判定(内核模块):
    return 内核模块('公告认领').判定公告认领


@pytest.fixture(scope='module')
def 公告(内核模块):
    return 内核模块('解析_公告')


def 成员(名, **覆盖):
    m = {'事件名': 名, '显示名': 名, '公告页': '公告', '锚点': None,
         '类型': 1, '开始': '2099-01-01 00:00:00',
         '结束': '2099-12-31 23:59:00', '已结束': False}
    m.update(覆盖)
    return m


def 板块(公告, 标题, **覆盖):
    参数 = dict(标题=标题, 窗口=('2026-11-01 12:00:00', '2026-11-22 03:59:00'),
              关卡各段=[], 类型=1, 是主体=False)
    参数.update(覆盖)
    return 公告.板块(**参数)


def 快照(结果, 全板块):
    # 索引随板块重排改变，语义关联集合不变；这里的 id 也只在本次测试内。
    return (frozenset((全板块[i][0], id(全板块[i][1]), id(m))
                      for i, m in 结果.认领.items()),
            结果.已领, 结果.争议成员, 结果.无时间成员, 结果.诊断)


def 检查排列(判定, 成员们, 全板块):
    预期 = 快照(判定(成员们, 全板块), 全板块)
    for 成员序 in permutations(成员们):
        for 板块序 in permutations(全板块):
            assert 快照(判定(list(成员序), list(板块序)), 板块序) == 预期
    return 判定(成员们, 全板块)


def test_两成员标题同级争同块全部不认领(判定, 公告):
    a, b = 成员('活动'), 成员('活动开启')
    r = 检查排列(判定, [a, b], [('公告', 板块(公告, '活动开启'))])
    assert r.认领 == {} and r.已领 == set()
    assert r.争议成员 == {id(a), id(b)}


def test_三成员两强同级冲突弱者不能捡漏(判定, 公告):
    a, b = 成员('甲', 锚点='活动开启'), 成员('乙', 锚点='活动开启')
    c = 成员('活动')
    r = 检查排列(判定, [a, b, c], [('公告', 板块(公告, '活动开启'))])
    assert r.认领 == {} and r.争议成员 == {id(a), id(b), id(c)}


def test_三成员三板块独立认领集合不随顺序变(判定, 公告):
    ms = [成员('甲'), 成员('乙'), 成员('丙')]
    bs = [('公告', 板块(公告, 名 + '开启')) for 名 in '甲乙丙']
    r = 检查排列(判定, ms, bs)
    assert len(r.认领) == 3 and r.争议成员 == set()


def test_唯一锚点优先于自身标题(判定, 公告):
    m = 成员('甲', 锚点='乙开启')
    bs = [('公告', 板块(公告, '甲开启')), ('公告', 板块(公告, '乙开启'))]
    r = 检查排列(判定, [m], bs)
    assert r.认领 == {1: m}


def test_唯一锚点优先于弱标题竞争(判定, 公告):
    a, b = 成员('甲', 锚点='乙开启'), 成员('乙', 类型=99)
    r = 检查排列(判定, [a, b], [('公告', 板块(公告, '乙开启'))])
    assert r.认领[0] is a and r.已领 == {id(a)}
    assert r.争议成员 == {id(b)}  # lead 必须禁止长期 ask 掩盖弱竞争。


def test_重复锚点不得降级唯一标题(判定, 公告):
    m = 成员('甲', 锚点='重复')
    bs = [('公告', 板块(公告, '重复')), ('公告', 板块(公告, '重复')),
          ('公告', 板块(公告, '甲开启'))]
    r = 检查排列(判定, [m], bs)
    assert r.认领 == {} and r.争议成员 == {id(m)}


def test_歧义强锚点保留所有候选块(判定, 公告):
    a, b = 成员('甲', 锚点='重复'), 成员('重复')
    # 第二块时间不可接管也不能按可生成性筛掉，成为伪唯一。
    bs = [('公告', 板块(公告, '重复')), ('公告', 板块(公告, '重复', 窗口=None))]
    r = 检查排列(判定, [a, b], bs)
    assert r.认领 == {} and r.争议成员 == {id(a), id(b)}


def test_锚点仅匹配指定页(判定, 公告):
    m = 成员('甲', 锚点='明确')
    bs = [('其它页', 板块(公告, '明确')), ('公告', 板块(公告, '明确'))]
    r = 检查排列(判定, [m], bs)
    assert r.认领 == {1: m} and not r.诊断


def test_零匹配锚点允许指定页唯一标题兜底并诊断(判定, 公告):
    m = 成员('甲', 锚点='旧锚点')
    bs = [('其它页', 板块(公告, '甲开启')), ('公告', 板块(公告, '甲开启'))]
    r = 检查排列(判定, [m], bs)
    assert r.认领 == {1: m}
    assert any('零匹配' in d and '唯一标题兜底' in d for d in r.诊断)


def test_同成员标题多板块不按同窗或剩余块猜(判定, 公告):
    a, b = 成员('甲'), 成员('其它', 锚点='甲一阶段')
    bs = [('公告', 板块(公告, '甲一阶段')), ('公告', 板块(公告, '甲二阶段'))]
    r = 检查排列(判定, [a, b], bs)
    assert r.认领 == {0: b} and r.争议成员 == {id(a)}


def test_不同对象相同字典不折叠并诊断(判定, 公告):
    a = 成员('甲')
    b = dict(a)
    assert a == b and a is not b
    r = 检查排列(判定, [a, b], [('公告', 板块(公告, '甲开启'))])
    assert r.认领 == {} and r.争议成员 == {id(a), id(b)}
    assert any('内容完全相同' in d and '身份别名未确认' in d for d in r.诊断)
    assert r.诊断 == tuple(sorted(r.诊断))
    assert all(str(id(m)) not in d for d in r.诊断 for m in [a, b])


def test_无候选不以相同ask时间认领(判定, 公告):
    m = 成员('完全无关', 开始='2026-11-01 12:00:00', 结束='2026-11-22 03:59:00')
    r = 判定([m], [('公告', 板块(公告, '另一活动'))])
    assert r.认领 == {} and r.已领 == set() and r.争议成员 == set()


def test_无总窗阶段仍可认领(判定, 公告):
    (b,) = 公告.抽板块(
        '==SideStory「甲」活动关卡开启==\n'
        '活动关卡将进行分段式开启：\n'
        '◆【第一章】开启时间：11月01日 12:00 - 11月22日 03:59\n', datetime(2026, 11, 1))
    b.窗口 = None
    m = 成员('甲')
    r = 判定([m], [('公告', b)])
    assert r.认领 == {0: m} and r.已领 == {id(m)}
    条目 = 公告.局部时间条目(b, '父', m['显示名'], m['类型'])
    assert 条目 and [e['名称'] for e in 条目] == ['甲·一阶段']
    assert 条目[0]['开始时间'] == '2026-11-01 12:00:00'


def test_不安全阶段适用空选项仍接管不ask(判定, 公告, 内核模块):
    (b,) = 公告.抽板块(
        '==【甲】活动开启==\n'
        '活动分为预选期和招募期\n'
        '◆预选期：11月01日 12:00 - 11月03日 03:59\n', datetime(2026, 11, 1))
    b.窗口 = None
    选择 = 内核模块('公告时间选用').选用公告时间(b.局部识别, b.是主体)
    assert 选择.适用 is True and 选择.选项 == ()
    m = 成员('甲', 类型=99)
    r = 判定([m], [('公告', b)])
    assert r.认领 == {0: m} and r.已领 == {id(m)}
    assert 公告.局部时间条目(b, '父', m['显示名'], m['类型']) == []


def test_唯一候选无可接管时间单独分类且不改认标题(判定, 公告):
    m = 成员('甲', 锚点='显式', 类型=99)
    bs = [('公告', 板块(公告, '显式', 窗口=None)), ('公告', 板块(公告, '甲开启'))]
    r = 检查排列(判定, [m], bs)
    assert r.认领 == {} and not r.争议成员 and r.无时间成员 == {id(m)}
    assert any('禁止ask兜底' in d for d in r.诊断)


def test_输入不变且相同对象重复不是竞争(判定, 公告):
    m = 成员('甲')
    bs = [('公告', 板块(公告, '甲开启'))]
    before = deepcopy(([m, m], bs))
    r = 判定([m, m], bs)
    assert r.认领[0] is m and not r.争议成员
    assert ([m, m], bs) == before


def test_争议板块保持未认领供源事实自生成(判定, 公告):
    a, b = 成员('限时'), 成员('任务')
    (board,) = 公告.抽板块(
        '==「限时任务」活动开启==\n活动时间：11月01日 12:00 - 11月22日 03:59',
        datetime(2026, 11, 1))
    r = 判定([a, b], [('公告', board)])
    assert not r.认领
    条目 = 公告.板块条目(board, '父')
    assert len(条目) == 1 and 条目[0]['名称'] == '限时任务'
    assert 条目[0]['开始时间'] == '2026-11-01 12:00:00'
