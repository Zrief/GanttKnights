def test_缺失子类型列时读CSV会自动反推(tmp_path) -> None:
    """旧 CSV（没有 子类型 列）读进来也要能分组。⚠️ 这条随反推逻辑一起作废（见该函数时效注释）。"""
    csv = tmp_path / "所有活动数据.csv"
    csv.write_text(
        "名称,开始时间,结束时间,类型,来源\n"
        "【中坚池】#74 · 艾雅法拉 / 风笛,2026-09-24 04:00:00,2026-10-08 03:59:00,0,\n",
        encoding="utf-8-sig",
    )
    记录 = preprocess_data(str(csv), now=datetime(2026, 9, 24), left_border=datetime(2026, 9, 20),
                           right_border=datetime(2026, 10, 12))
    assert [e.子类型 for e in 记录] == ["中坚"]


def test_带子类型列时直接读列(tmp_path) -> None:
    csv = tmp_path / "所有活动数据.csv"
    csv.write_text(
        "名称,开始时间,结束时间,类型,子类型,来源\n"
        "【中坚池】#74 · 艾雅法拉 / 风笛,2026-09-24 04:00:00,2026-10-08 03:59:00,0,甄选,\n",
        encoding="utf-8-sig",
    )
    记录 = preprocess_data(str(csv), now=datetime(2026, 9, 24), left_border=datetime(2026, 9, 20),
                           right_border=datetime(2026, 10, 12))
    assert [e.子类型 for e in 记录] == ["甄选"]      # 列里写了什么就是什么，不再反推


def test_卡池按子类型成块且限时在上():
    """渲染层 `reversed(排序)` 之后的左列次序 = 限时 → 中坚 → 标准 → 甄选（图上从上到下）。"""
    条目们 = [
        活动("c", datetime(2026, 9, 24), datetime(2026, 10, 1), 0, "标准"),
        活动("a", datetime(2026, 9, 24), datetime(2026, 10, 1), 0, "限时"),
        活动("d", datetime(2026, 9, 24), datetime(2026, 10, 1), 0, "甄选"),
        活动("b", datetime(2026, 9, 24), datetime(2026, 10, 1), 0, "中坚"),
    ]
    图上 = list(reversed(sorted(条目们, key=排序键, reverse=True)))
    assert [e.名称 for e in 图上] == ["a", "b", "c", "d"]


def test_合并保存CSV写回子类型(tmp_path) -> None:
    """CSV 契约：新列要落到表头与行里，下一次读才能直接拿到（而不是又去反推）。"""
    from src.汇总_活动 import 合并保存CSV

    csv = tmp_path / "所有活动数据.csv"
    合并保存CSV(
        [{"名称": "【中坚池】#74 · 艾雅法拉 / 风笛", "开始时间": "2026-09-24 04:00:00",
          "结束时间": "2026-10-08 03:59:00", "类型": 0, "子类型": "中坚"}],
        csv, "2026-09-24 20:00:00", 允许大幅清理=True,
    )
    import csv as csv模块

    with csv.open(encoding="utf-8-sig", newline="") as f:
        行 = list(csv模块.DictReader(f))
    assert 行[0]["子类型"] == "中坚"
