def 原文(名称):
    return (原文目录 / f"{名称}.wikitext").read_text(encoding="utf-8")


def 切板块(文本, 标题词="SideStory"):
    """独立按层级切原文，保留正文第一行号，避免混入同页其他活动。"""
    标题式 = re.compile(r"^(={1,6})(.+?)\1\s*$", re.M)
    标题们 = list(标题式.finditer(文本))
    for i, 标 in enumerate(标题们):
        if 标题词 not in 标[2]:
            continue
        止 = next((后.start() for 后 in 标题们[i + 1:]
                   if len(后[1]) <= len(标[1])), len(文本))
        return 文本[标.start():止], 文本[标.end():止], 文本.count("\n", 0, 标.end()) + 1
    raise AssertionError(f"样本缺少板块：{标题词}")


def 样本板块(公告, 名称="感谢庆典2026", 年份=2026, 标题词="SideStory"):
    片, _, _ = 切板块(原文(名称), 标题词)
    (b,) = 公告.抽板块(片, datetime(年份, 7, 1))
    return b


def 窗口(年份, 起, 止):
    return (f"{年份}-{起}:00", f"{年份}-{止}:00")


def 行快照(条目们):
    return [(e["名称"], (e["开始时间"], e["结束时间"])) for e in 条目们]


def 成员(事件名, 显示名, 页, 锚点=None):
    return {"事件名": 事件名, "显示名": 显示名,
            "开始": "2099-01-01 00:00:00", "结束": "2099-12-31 23:59:00",
            "类型": 1, "已结束": False, "公告页": 页, "锚点": 锚点}


