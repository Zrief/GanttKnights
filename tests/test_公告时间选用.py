@pytest.mark.parametrize("样本,年份,活动名,总窗,阶段,区域们", 真实预期,
                         ids=[row[0] for row in 真实预期])
def test_六份真实主体选用保持总窗战斗契约而生产增量商店(公告, 选用, 样本, 年份, 活动名, 总窗, 阶段, 区域们):
    b = 样本板块(公告, 样本, 年份)
    结果 = 选用(b.局部识别, True)
    assert 结果.适用 is True
    期望窗 = ([窗口(年份, *总窗)] if 总窗 else []) + [窗口(年份, *段) for 段 in 阶段]
    assert [项.窗口 for 项 in 结果.选项] == 期望窗
    本名 = f"SideStory「{活动名}」"
    期望名 = ([本名] if 总窗 else []) + [f"{本名}·{字}阶段" for 字 in "一二三"[:len(阶段)]]
    条目们 = 公告.板块条目(b, 活动名)
    assert 行快照([e for e in 条目们 if e["_原角色"] != "兑换开放"]) == list(zip(期望名, 期望窗))
    商店窗, 商店对象 = 商店预期[样本]
    期望生产 = list(zip(期望名, 期望窗))
    if 商店窗:
        期望生产.append((本名 + "·商店", 窗口(年份, *商店窗)))
    assert 行快照(条目们) == 期望生产
    assert all(项.角色 != "兑换开放" for 项 in 结果.选项)
    商店们 = [e for e in 条目们 if e["_原角色"] == "兑换开放"]
    assert len(商店们) == int(商店窗 is not None)
    if 商店们:
        assert 商店们[0]["_原对象"] == (商店对象,)
        assert 商店们[0]["_阶段序号"] == 0 and 商店们[0]["_活动本名"] == 本名
    assert all(e["类型"] == 1 and e["_parent"] == 活动名 for e in 条目们)
    assert not any(区域 in e["名称"] for 区域 in 区域们 for e in 条目们)
    assert not any("关卡" in e["名称"] or "兑换" in e["名称"] for e in 条目们)
    if 样本 == "生路2025":
        assert b.局部识别.阶段记录[0].对象 == ("信标投放", "防线巩固")
        assert len(条目们) == 3  # 总窗、一条两区域共窗阶段、独立商店；不拆成两阶段。
    if 样本 == "感谢庆典2025":
        assert b.局部识别.阶段记录[0].窗口 is None
        兑换记录 = [r for r in b.局部识别.局部记录 if r.角色 == "兑换开放"]
        assert len(兑换记录) == 1 and 兑换记录[0].窗口 is None
        assert 兑换记录[0].对象 == (商店对象,)
        assert 结果.原因  # 不允许将精准的二、三段缩成伪完整活动。


