@pytest.mark.parametrize("变体", ["缺阶段", "窗口冲突", "未知角色"])
def test_不安全流程禁止回退旧总览且选择原因可访问(公告, 选用, 变体):
    片, _, _ = 切板块(原文("感谢庆典2026"), "感谢庆典特别招募活动开启")
    if 变体 == "缺阶段":
        片 = 片.replace("◆招募期：11月01日 12:00 - 12月02日 03:59", "")
    elif 变体 == "窗口冲突":
        片 = 片.replace("◆招募期：11月01日 12:00 - 12月02日 03:59",
                        "◆招募期：11月01日 12:00 - 12月05日 03:59")
    else:
        片 = 片.replace("◆预选期：10月24日", "◆预选期\n兑换时间：10月24日")
    (b,) = 公告.抽板块(片, datetime(2026, 11, 1))
    assert b.窗口 is not None  # 旧明示总窗仍存在，不能因此生成旧总览。
    结果 = 选用(b.局部识别, False)
    assert 结果.适用 is True and 结果.选项 == ()
    assert isinstance(结果.原因, tuple) and 结果.原因
    assert all(isinstance(原因, str) and 原因 for 原因 in 结果.原因)
    assert 公告.局部时间条目(b, "感谢庆典2026") == []
    assert 公告.板块条目(b, "感谢庆典2026") == []


