"""节点提醒：只在"配置的天数节点"上说话（`src/生成_提醒.py`）。

判据是"**今天的日期与活动时间窗的关系**"，所以每个用例都把"今天"注入成固定日期——
不注入就没法测"昨天 / 今天 / 下周"这种跨天行为。

第一条用例就是用户给的例子（2026-09-15）：
    昨天有 A（今天结束）、B（明天结束）、C（持续中），今天爬到 D（下周才开）
    → 昨天只提醒 A；今天只提醒 B；D 要到它开启那天才提醒。

（本模块的 `gk.*` 只能在 fixture 里导入：合成包由 `conftest.py` 的 session fixture 建，
 收集测试模块时还不存在。）
"""

from __future__ import annotations

from datetime import datetime
from types import SimpleNamespace

import pytest


@pytest.fixture(scope="module")
def 工具(内核模块) -> SimpleNamespace:
    活动类 = 内核模块("活动").活动
    生成提醒 = 内核模块("生成_提醒").生成提醒

    def 造(名: str, 开始: str, 结束: str, 类型: int = 1):
        return 活动类(名称=名, 开始=datetime.fromisoformat(开始),
                      结束=datetime.fromisoformat(结束), 类型=类型)

    # 09-14 那天的数据：A 今天(09-15)结束、B 明天(09-16)结束、C 长期、D 下周(09-22)开
    三天 = [
        造("A活动", "2026-09-01 04:00", "2026-09-15 03:59", 0),
        造("B活动", "2026-09-02 04:00", "2026-09-16 03:59", 1),
        造("C长期", "2026-08-01 04:00", "2026-10-30 03:59", 99),
        造("D活动", "2026-09-22 16:00", "2026-10-06 03:59", 0),
    ]
    return SimpleNamespace(造=造, 生成提醒=生成提醒, 三天=三天,
                           D=三天[3],
                           昨=datetime(2026, 9, 14, 8, 0),
                           今=datetime(2026, 9, 15, 8, 0))


def test_用户给的三天推演(工具):
    assert 工具.生成提醒(工具.三天, 现在时间=工具.昨) == "⚠️ 明天结束\n🎯 A活动"
    assert 工具.生成提醒(工具.三天, 现在时间=工具.今) == "⚠️ 明天结束\n📅 B活动"
    assert 工具.生成提醒([工具.D], 现在时间=datetime(2026, 9, 22, 8, 0)) == "🔥 今天开启\n🎯 D活动"


def test_阈值天与最后一天各响一次(工具):
    """默认 `结束偏移们=(-3, -1)`：结束前 3 天响一次、最后一天再响一次，中间的日子沉默。"""
    事件 = [工具.造("活动", "2026-09-01 04:00", "2026-09-18 03:59")]
    话 = {剩: 工具.生成提醒(事件, 现在时间=datetime(2026, 9, 18 - 剩, 8, 0))
          for 剩 in (4, 3, 2, 1)}
    assert 话[4] == "" and 话[2] == "", "不在节点上就该一个字都不说"
    assert 话[3] == "3 天后结束\n📅 活动"
    assert 话[1] == "⚠️ 明天结束\n📅 活动"
    # 结束当天（剩 0）不在默认数组里 → 不提醒
    assert 工具.生成提醒(事件, 现在时间=datetime(2026, 9, 18, 8, 0)) == ""


def test_偏移完全可配(工具):
    """数组就是策略：想在结束当天、结束前一周、开启前一天提醒，都只是改配置。"""
    长活动 = [工具.造("活动", "2026-09-01 04:00", "2026-09-18 03:59")]
    assert 工具.生成提醒(长活动, 现在时间=datetime(2026, 9, 11, 8, 0), 结束偏移们=(-7,)) \
        == "7 天后结束\n📅 活动"
    assert 工具.生成提醒(长活动, 现在时间=datetime(2026, 9, 18, 8, 0), 结束偏移们=(0,)) \
        == "🔥 今天结束\n📅 活动"
    新活动 = [工具.造("新活动", "2026-09-22 16:00", "2026-10-06 03:59")]
    assert 工具.生成提醒(新活动, 现在时间=datetime(2026, 9, 21, 8, 0), 开始偏移们=(-1,)) \
        == "⚠️ 明天开启\n📅 新活动"


def test_空数组等于这一类不提醒(工具):
    assert 工具.生成提醒(工具.三天, 现在时间=工具.今, 结束偏移们=()) == ""
    assert 工具.生成提醒(工具.三天, 现在时间=工具.今,
                         结束偏移们=(), 开始偏移们=()) == ""


def test_一次最多列十行(工具):
    一堆 = [工具.造(f"活动{i:02d}", "2026-09-01 04:00", "2026-09-16 03:59") for i in range(12)]
    行 = 工具.生成提醒(一堆, 现在时间=工具.今).splitlines()
    assert 行[0] == "⚠️ 明天结束" and len(行) == 1 + 10 + 1   # 组头 + 10 行 + 省略行
    assert 行[-1] == "…另有 2 项"
    assert all("活动" in 项 for 项 in 行[1:11])


def test_分组顺序_结束在前_当天在前(工具):
    记录 = [工具.造("今天开的", "2026-09-15 16:00", "2026-09-29 03:59"),
            工具.造("三天后结束", "2026-09-01 04:00", "2026-09-18 03:59"),
            工具.造("明天结束", "2026-09-01 04:00", "2026-09-16 03:59")]
    assert 工具.生成提醒(记录, 现在时间=工具.今).splitlines() == [
        "⚠️ 明天结束", "📅 明天结束",
        "3 天后结束", "📅 三天后结束",
        "🔥 今天开启", "📅 今天开的",
    ]


def test_单日活动只报开启(工具):
    """开始=结束=今天：只进"今天开启"，不该同时冒出一句"今天结束"（默认数组里也没有 0）。"""
    单日 = [工具.造("单日", "2026-09-15 04:00", "2026-09-15 23:59")]
    assert 工具.生成提醒(单日, 现在时间=工具.今) == "🔥 今天开启\n📅 单日"


def test_没有活动或没有节点都返回空串(工具):
    assert 工具.生成提醒([], 现在时间=工具.今) == ""
    assert 工具.生成提醒(工具.三天, 现在时间=datetime(2026, 9, 10, 8, 0)) == ""


def test_同一天渲染多次结果一致(工具):
    """无状态：文案只取决于"今天 + 数据 + 配置"，所以重复渲染不会漂。"""
    一 = 工具.生成提醒(工具.三天, 现在时间=工具.今)
    二 = 工具.生成提醒(工具.三天, 现在时间=datetime(2026, 9, 15, 23, 30))
    assert 一 == 二 == "⚠️ 明天结束\n📅 B活动"


def test_不传现在时间也不炸(工具):
    assert isinstance(工具.生成提醒(工具.三天), str)
