"""指令元数据 —— 命令名 / 别名 / 子命令表 / 帮助条目的**唯一来源**。

只有**一条**注册命令 `/方舟日程`，其余用法全是它的子命令（指令后空格分隔的
第一个词）。注册的命令越少，用户要记的越少、README 的表越短、指令之间也不会
串味（2026-09-27 定；原先是七条独立命令、两套命名混用）。

子命令不是本插件自己解析的：宿主的 CommandFilter 会把指令后的参数按 handler
签名填进来（`子命令: str = ""` 收第一个词），我们只做分发。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class CommandSpec:
    """注册命令的元数据（`name` 不含前导斜杠——AstrBot 的指令名本来就不带）。"""

    name: str
    aliases: tuple[str, ...] = ()

    @property
    def alias_set(self) -> set[str]:
        """给 `@filter.command(name, alias=...)` 用（框架要求 set）。"""
        return set(self.aliases)


@dataclass(frozen=True)
class 子命令Spec:
    """`/方舟日程 X` 里的 X。"""

    名: str
    summary: str
    管理员: bool = False


甘特图命令 = CommandSpec(
    name="方舟日程",
    aliases=("方舟甘特",),
)
"""唯一的注册命令。主指令叫「方舟日程」而不是「甘特图」：它是给用户看的东西
（"今天有什么日程"），「甘特图」只是画法。别名照旧可用：`/方舟甘特 订阅`。"""

出图说明 = "出图：近期活动一览（首次会抓取数据，之后几秒）。"

子命令表: tuple[子命令Spec, ...] = (
    子命令Spec("订阅", "把当前会话加入每日推送（群聊、私聊都可以，多个会话各订各的）。"),
    子命令Spec("退订", "把当前会话移出每日推送。"),
    子命令Spec("状态", "数据更新时间、最近一次变化、推送情况、本会话标识。"),
    子命令Spec("刷新", "数据不对劲/怀疑没更新时先用它：强制重新抓取并重画。", 管理员=True),
    子命令Spec("初始化", "全量重建数据：补录剿灭轮换、复刻排期，平时用不到。", 管理员=True),
    子命令Spec("帮助", "这条帮助。"),
)


def 生成帮助文本(版本: str) -> str:
    """帮助页（不手写第二份指令清单——由 `子命令表` 生成）。"""
    行们 = [
        f"明日方舟甘特图 v{版本}", "",
        "指令",
        "", f"/{甘特图命令.name}", 出图说明,
    ]
    for 子 in 子命令表:
        标注 = "（管理员）" if 子.管理员 else ""
        行们 += ["", f"/{甘特图命令.name} {子.名}{标注}", 子.summary]
    行们 += [
        "", "说明",
        "· 数据来自 PRTS Wiki，每天第一次出图时自动更新；数据看着缺内容时，让管理员发「/方舟日程 初始化」重建。",
        "· 时间窗、底栏面板、背景图、每日推送都在插件配置里改。",
        "· 每日推送发到配置里的推送目标：在要推送的会话里发「/方舟日程 订阅」加入、「/方舟日程 退订」移出，也能在设置页里增删。",
    ]
    return "\n".join(行们)
