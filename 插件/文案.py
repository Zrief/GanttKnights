def 说明素材缺失(exc) -> str:
    """`素材缺失` 异常 → 给用户看的一句话（区分"目录空"与"指定的文件不在"）"""
    if getattr(exc, "文件", ""):
        return 缺背景文件.format(文件=exc.文件)
    return 缺背景图.format(目录=exc.目录)
