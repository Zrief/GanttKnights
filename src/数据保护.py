"""数据保护 — 写回活动数据前的"防静默丢失"护栏。

为什么需要
---------
`合并保存CSV` 的清理线由**调用方传入的时间**推导：

    清理线 = 传入时间 - 过期保留天数

因此只要传入的时间偏新（例如调试时注入了一个未来/基准时间），
所有结束时间早于清理线的条目都会被判为"过期"清掉，写回时就可能只剩表头
——**而且不会有任何报错**。本项目开发期间真实触发过一次：注入 2026-09-13
的基准时间后，21 条数据被清空为 0 条。

护栏策略
--------
在真正写盘之前检查"已有条数 → 待写条数"的变化，命中以下任一情况即**拒绝写回**
（原文件保持不动），由调用方决定是告警还是用 `允许大幅清理=True` 显式放行：

1. 已有非空，而待写为空 —— 一次清空，几乎必然是时间传错；
2. 清理比例过高（见 `最大允许清理比例`），且已有条数达到 `比例检查下限条数`。

阈值刻意保守：宁可偶尔拦下一次合法的大清理（调用方显式放行即可），
也不要静默丢数据。
"""

from __future__ import annotations

from dataclasses import dataclass

# 已有条数达到这个量级才启用"比例"检查；条目很少时比例没有统计意义
比例检查下限条数 = 10
# 单次写回最多清掉这个比例的条目
最大允许清理比例 = 0.5


class 数据保护拦截(Exception):
    """写回被护栏拦下。原文件未被修改。"""


@dataclass(frozen=True)
class 判定:
    """护栏判定结果"""

    允许: bool
    原因: str

    def __bool__(self) -> bool:  # 便于 `if 判定(...)` 的写法
        return self.允许


def 判定写回(已有条数: int, 待写条数: int) -> 判定:
    """纯函数：判断"已有 → 待写"这次写回是否安全。

    只做条数层面的判断，不碰文件，便于单测。
    """
    if 已有条数 <= 0:
        return 判定(True, f'原文件为空或不存在，正常写入 {待写条数} 条')

    if 待写条数 <= 0:
        return 判定(
            False,
            f'本次写回会把 {已有条数} 条数据清空为 0 条。'
            f'最常见原因是传给 合并保存CSV 的「现在时间」比数据新，'
            f'导致全部条目被判为过期。如确实要清空，请显式传 允许大幅清理=True。',
        )

    清理条数 = 已有条数 - 待写条数
    if 清理条数 > 0 and 已有条数 >= 比例检查下限条数:
        比例 = 清理条数 / 已有条数
        if 比例 > 最大允许清理比例:
            return 判定(
                False,
                f'本次写回将清掉 {清理条数}/{已有条数} 条（{比例:.0%}），'
                f'超过单次上限 {最大允许清理比例:.0%}。'
                f'请确认「现在时间」是否正确；如确实要清理，请显式传 允许大幅清理=True。',
            )

    if 清理条数 > 0:
        return 判定(True, f'正常写回 {待写条数} 条（清理 {清理条数} 条）')
    return 判定(True, f'正常写回 {待写条数} 条（新增 {待写条数 - 已有条数} 条）')


def 校验写回(已有条数: int, 待写条数: int) -> None:
    """判定并拦截：不允许时抛 数据保护拦截（不写盘）。"""
    结果 = 判定写回(已有条数, 待写条数)
    if not 结果.允许:
        raise 数据保护拦截(结果.原因)
