"""解析层 — 把 SMW ask 的查询结果转成活动条目

**公告是唯一时间源，ask 只当电话簿**（2026-09-17 定；页面名/类型/粗窗口/分组）：
wiki 手填的 SMW 属性会抄错（实测 `稳态测定` 的窗口被抄成月行水上那批的），
而公告原文是运营公告的逐字转载。ask 时间只剩三个用途：30 天扫描过滤、
公告年份锚、无公告页条目（99 型常驻）的兜底。

认领顺序即降级顺序（`认领与生成`）：`公告=` 的 #板块锚点（wiki 的显式指认）→
板块标题含活动名 → （无公告页时）ask 粗窗口。**组里有公告页的，认不到段落就不生成**
——它的窗口由公告板块自生成的条目代表（2026-09-27 定：此前 ask 兜底会与板块自生成
条目同窗双行，矢量突破/03 在公告里叫「矢量突破#3「拟生态」」就是这么重复的）。
无人认领的板块（关卡◆/组合包/剿灭追加）照常自生成。
"""

from __future__ import annotations

import re
from datetime import datetime, timedelta

from . import 长期活动
from .获取_prts import 公告页标题, 获取页面wikitext
from .解析_公告 import 板块, 板块条目, 公告定位, 关卡条目, 页父名, 解析活动信息, 提醒保全, 抽板块
from .日志 import logger

# PRTS 的"活动开始/结束时间"存的是 UTC，比国服早 8 小时；
# cn 后缀属性是国服时间，但只有开始时间有，结束时间一律自己 +8h 换算
UTC国服差 = timedelta(hours=8)

近期窗口天 = 30
"""日常扫描的时间窗：**进行中的活动** + **结束时间在这个窗口内**的已结束活动。

流程（2026-09-14 与用户对齐）：**先初始化一份 CSV，之后只动态维护它**——
日常只扫"最近这部分"（新出现的加进来、过期的由合并删掉），
老活动的公告不会再变，没必要天天读。初始化（`回溯已结束=True`）才扫所有活动。

窗口取 30 天：剿灭轮换的公告随当期活动一起发（活动结束前就挂上了，属于"进行中"那类），
30 天足以覆盖"停几天机、活动刚结束"的情况；更老的靠初始化补齐。
"""

# ---------- API 活动类型 → 数值 ----------

API类型映射 = {
    "支线故事": 1, "主线": 1, "故事集": 1, "合作活动": 1,
    "其他活动": 1, "纪念活动": 1, "危机合约": 1,
    "矢量突破": 1, "争锋频道": 1, "纷争演绎": 1,
    "登录活动": 2, "签到": 2,
    # 长期玩法：字面量来自 src/长期活动.py（SMW「活动类型」的精确取值）
    **{字面量: 长期活动.类型值 for 字面量 in 长期活动.字面量们},
}

名称类型规则 = [
    (["寻访", "中坚", "甄选", "招募", "限定", "标准池", "中坚池", "跨年"], 0),
    (["战斗", "SideStory", "故事集", "资源收集", "复刻", "联动"], 1),
    (["签到", "赠送", "领取", "月卡", "专享", "补给"], 2),
    (["家具", "时装", "新装", "主题", "上架", "风尚"], -1),
    (list(长期活动.关键词们), 长期活动.类型值),
]


def 分类事件(API类型: str = "", 事件名: str = "") -> int:
    if API类型 and API类型 in API类型映射:
        return API类型映射[API类型]
    for 关键词列表, 类型 in 名称类型规则:
        for kw in 关键词列表:
            if kw in 事件名:
                return 类型
    return 1


def 长期显示名(api类型: str, 事件名: str) -> str | None:
    """长期条目的显示名 `官方名「对象名」`（卫戍协议·规程 → 卫戍协议「规程」）；
    页面名自带玩法名时剥掉、对象名用「」包（与官方 SideStory「XXX」同构）。
    非长期返回 None。"""
    官方名 = 长期活动.识别(api类型)
    if not 官方名:
        return None
    剥后 = re.sub(rf"^{re.escape(官方名)}[·：:\s]+", "", 事件名)
    if not 剥后:
        return 事件名
    return f"{官方名}「{剥后}」"


def 解析API时间戳(ts_info) -> str | None:
    """把 SMW 的 raw 时间转成 'YYYY-MM-DD HH:MM:00'

    raw 形如 1/2026/9/4/12/0/0，首段是日历标识（格里高利历=1）；
    兼容缺少首段的 6 段写法。
    """
    if isinstance(ts_info, dict):
        parts = ts_info.get("raw", "").split("/")
        if len(parts) >= 7:
            _, y, m, d, h, mi = parts[:6]
        elif len(parts) >= 6:
            y, m, d, h, mi = parts[:5]
        else:
            return None
        return f"{y}-{m.zfill(2)}-{d.zfill(2)} {h.zfill(2)}:{mi.zfill(2)}:00"
    return None


def 提取API时间(属性: dict, 键: str) -> str | None:
    值 = 属性.get(键)
    return 解析API时间戳(值[0]) if 值 else None


def 转国服时间(时间串: str | None) -> str | None:
    if not 时间串:
        return None
    t = datetime.strptime(时间串, "%Y-%m-%d %H:%M:%S") + UTC国服差
    return t.strftime("%Y-%m-%d %H:%M:%S")


def 提取官网链接(属性: dict) -> str:
    """官网公告标识：同一官方公告的活动（如月行水上和它的登录活动此夜同行）
    共享一个链接 id。无则返回空串。"""
    值 = 属性.get("官网链接")
    if not 值:
        return ""
    v = 值[0]
    return str(v.get("raw", "")).strip() if isinstance(v, dict) else str(v).strip()


def 是网页活动(属性: dict) -> bool:
    """挂 分类:网页活动 的是浏览器/H5 页面（冻土与火种这类抽奖/召回页），
    不是游戏内排期——不上图（2026-10-28 用户定）。"""
    return any("网页活动" in c.get("fulltext", "") for c in 属性.get("分类", []))


def 认领与生成(成员们: list[dict], 页们: dict[str, list[板块]]) -> list[dict]:
    """组内的三层认领与条目生成（**纯函数**：网络与页面定位由调用方负责，测试直接喂字典）。

    成员字段：事件名 / 显示名 / 开始 / 结束 / 类型 / 已结束 / 公告页 / 锚点。
    每个成员至多认领一个板块，每个板块至多被一个成员认领。
    """
    全板块 = [(页名, b) for 页名, 表 in 页们.items() for b in 表]
    认领: dict[int, dict] = {}       # 板块序号 → 成员
    已领: set[int] = set()           # 已认领成员的 id()

    def 试认领(m: dict, i: int, b: 板块, 方式: str) -> bool:
        if i not in 认领 and b.窗口:
            认领[i] = m
            已领.add(id(m))
            logger.debug("  %s ← 板块「%s」（%s认领）", m["显示名"], b.标题, 方式)
            return True
        return False

    for m in 成员们:                                 # ① 锚点：wiki 的显式指认（只在该成员指的页里找）
        if m["锚点"]:
            for i, (页名, b) in enumerate(全板块):
                if 页名 == m["公告页"] and b.标题 == m["锚点"] and 试认领(m, i, b, "锚点"):
                    break
    for m in 成员们:                                 # ② 板块标题含事件名
        if id(m) not in 已领:
            for i, (_, b) in enumerate(全板块):
                if m["事件名"] in b.标题 and 试认领(m, i, b, "标题"):
                    break

    结果 = []
    已占窗: set[tuple[str, str]] = set()

    def 收组(条目们: list[dict], 认领条: bool = False) -> None:
        """同组内、跨板块，窗口一字不差的类型 1 条目只留先到的一条（公告章节顺序，
        主活动总在最前）：如矢量突破的「资源收集关卡全天开放」与主线同窗，生成只是
        图上多一条重复条。只在类型 1 之间去重——池/签到条不占窗，否则会误杀同窗的
        其他类型条目；同一板块自己的多条产出（主体 + 它的关卡段）互不去重；
        认领条（成员的代表条）永远保留，但也占窗，挡住之后到来的同窗自生成条。"""
        基线 = set(已占窗)
        for e in 条目们:
            窗 = (e["开始时间"], e["结束时间"])
            if e["类型"] == 1 and not 认领条 and 窗 in 基线:
                logger.debug("  %s 窗口与已有条目完全重合，不生成", e["名称"])
                continue
            if e["类型"] == 1:
                已占窗.add(窗)
            结果.append(e)

    for i, (页名, b) in enumerate(全板块):
        父名 = 页父名(页名)
        m = 认领.get(i)
        if m is None:
            收组(板块条目(b, 父名))
            continue
        收组([{"名称": m["显示名"], "开始时间": b.窗口[0], "结束时间": b.窗口[1],
               "类型": m["类型"], "_parent": 父名}], 认领条=True)
        if 关卡 := 关卡条目(b, 父名):                 # 被认领的主体板块，其 ◆ 段照常出一条 关卡
            收组([关卡], 认领条=True)

    for m in 成员们:                                 # ③ 无公告页 → ask 粗窗口兜底
        if id(m) in 已领:
            continue
        if 页们 and m["类型"] != 长期活动.类型值:
            # 组里有公告页：公告是唯一时间源，认不到段落就不生成（2026-09-27 定，
            # 起因：矢量突破/03 在公告里叫「矢量突破#3「拟生态」」，字面对不上号 →
            # ask 兜底又生成一条，和板块自生成的「拟生态」同窗双行）。
            # 它的窗口由公告板块自生成的条目代表；名字土一点没关系，出自公告就行。
            # 长期（99）例外（2026-10-28 卫戍协议）：常驻的窗口就该用 ask 整段
            # 时间，而它的板块抽不出对象名（见 解析_公告._长期任务名）不会自生成，
            # 压制它条目就没了。
            logger.debug("  %s → 公告未认领，不生成（由板块自生成条目代表）", m["显示名"])
            continue
        if m["已结束"]:
            logger.debug("  %s → 未认领（已结束，不添加）", m["显示名"])
        else:
            结果.append({"名称": m["显示名"], "开始时间": m["开始"], "结束时间": m["结束"],
                        "类型": m["类型"], "_parent": ""})
            logger.debug("  %s → ask 时间（类型 %s，无公告页兜底）", m["显示名"], m["类型"])
    return 结果


def API转活动列表(api原始: list[dict], 现在时间: str, 回溯已结束: bool = False) -> list[dict]:
    """SMW ask 结果 → 活动条目列表（机制见模块 docstring）

    - `回溯已结束=False`（日常）：只看**进行中 + 近期窗口内结束过**的活动；
    - `回溯已结束=True`（初始化：CLI `--bootstrap` / `/方舟日程 初始化`）：看**所有**活动。

    公告页会被**追加**内容（新的剿灭轮换写在当期活动的公告里），所以看得到的组
    每次都重读公告——公告也是我们唯一的显示时间来源。

    新增与过期不在这里判断：交给下游 `合并保存CSV`（它拿这个列表和昨天的 CSV 合并，
    有新增就加、过期就删）。
    """
    现在dt = datetime.strptime(现在时间, "%Y-%m-%d %H:%M:%S")
    窗口线 = (现在dt - timedelta(days=近期窗口天)).strftime("%Y-%m-%d %H:%M:%S")

    # 整理成员：ask 只提供身份（名称/类型/分组）与粗窗口（过滤 + 年份锚）
    待处理: list[dict] = []
    for 事件名, 条目 in api原始:
        属性 = 条目.get("printouts", {})
        if 是网页活动(属性):
            logger.debug("  %s → 网页活动（浏览器/H5 页面），不上图", 事件名)
            continue
        开始 = 提取API时间(属性, "活动开始时间cn") or 转国服时间(提取API时间(属性, "活动开始时间"))
        结束 = 转国服时间(提取API时间(属性, "活动结束时间"))
        if not (开始 and 结束):
            continue
        已结束 = 结束 <= 现在时间
        if 已结束 and not (回溯已结束 or 结束 >= 窗口线):
            continue
        api类型 = (属性.get("活动类型") or [None])[0] or ""
        # 长期玩法用官方名当前缀（左列只写「长期」，玩法信息得靠名字带）；
        # 前缀与识别来自 src/长期活动.py —— 剿灭/保全 也一起走，不再只挑肉鸽/联动
        if (长期名 := 长期显示名(api类型, 事件名)):
            显示名 = 长期名
        elif api类型 == "合作活动":
            显示名 = f"联动「{事件名}」"
        else:
            显示名 = 事件名
        开始dt = datetime.strptime(开始, "%Y-%m-%d %H:%M:%S")
        结束dt = datetime.strptime(结束, "%Y-%m-%d %H:%M:%S")
        待处理.append({
            "事件名": 事件名,
            "显示名": 显示名,
            "开始": 开始,
            "结束": 结束,
            "类型": 分类事件(API类型=api类型 or "", 事件名=事件名),
            "api类型": api类型,
            "已结束": 已结束,
            "组": 提取官网链接(属性) or 显示名,
            # 公告里多数只写"X月X日"：定年份要拿**父活动的时间窗中点**当基准
            # （用"今天"当基准会把老公告算成今年，见 解析_公告.解析时间）
            "参考": 开始dt + (结束dt - 开始dt) / 2,
        })

    # 逐成员读活动页本体的 {{活动信息}}，拿 公告= 指认（长期常驻没有公告页，跳过）
    for m in 待处理:
        m["公告页"] = m["锚点"] = None
        m["本体文本"] = None
        if m["类型"] != 长期活动.类型值:
            文本 = 获取页面wikitext(m["事件名"])
            m["本体文本"] = 文本
            信息 = 解析活动信息(文本 or "")
            if 信息.get("公告"):
                m["公告页"], m["锚点"] = 公告定位(信息["公告"])
            # 支线故事的官方全名带 SideStory 前缀（名称=SideStory「时间啊，向前！」），
            # 页面名/名称缩短都把它丢了——图上直接用官方全名，前缀形态
            # （裸前缀 + 「」包名）正是统一的样式（2026-10-29 定）
            if m["api类型"] == "支线故事" and 信息.get("名称"):
                m["显示名"] = 信息["名称"]

    分组: dict[str, list[dict]] = {}
    for t in 待处理:
        分组.setdefault(t["组"], []).append(t)

    公告缓存: dict[tuple[str, datetime], list[板块]] = {}

    def 取公告(页名: str, 参考: datetime) -> list[板块]:
        """读一份公告页 → 板块表；读不到 → 空表。缓存键带**参考窗**：
        同一份公告可能被复刻页指回，年份锚不同则解析结果不同，不能共用。"""
        键 = (页名, 参考)
        if 键 not in 公告缓存:
            wikitext = 获取页面wikitext(页名)
            公告缓存[键] = 抽板块(wikitext, 参考) if wikitext else []
        return 公告缓存[键]

    活动列表: list[dict] = []
    for 成员们 in 分组.values():
        # 长期排最后（2026-10-28 卫戍协议改赛季常驻后归入长期）：它的窗口整年，
        # 不该由它当主成员——默认公告页取它的、共享公告的年份锚取它的中点，
        # 都会把短活动的日期带偏一年
        成员们.sort(key=lambda m: (m["类型"] == 长期活动.类型值, m["类型"] == 2, m["已结束"]))
        # 组的公告页：成员 公告= 指的页；没人写过才退回主成员的默认公告页
        候选们 = [m["公告页"] for m in 成员们 if m["公告页"]]
        if not 候选们 and 成员们[0]["类型"] != 长期活动.类型值:
            候选们 = [公告页标题(成员们[0]["事件名"])]
        页们 = {页: 表 for 页 in dict.fromkeys(候选们)
               if (表 := 取公告(页, 成员们[0]["参考"]))}
        if not 页们 and (本体 := 成员们[0]["本体文本"]):
            # 公告页全落空时，试**活动页本体**——有的活动把整份公告直接写在
            # 页面自己的章节里（恒远津梁：{{活动信息}} 没写 公告=、
            # `X/活动公告` 子页也没建，公告就是页面正文的 == 章节）。
            # 文本在上一循环已读过，这里零新增请求；也只在别的全失败时兜底
            # （正常组不会把活动页的游戏说明章节误当公告）
            if (表 := 抽板块(本体, 成员们[0]["参考"])):
                页们 = {成员们[0]["事件名"]: 表}
        活动列表.extend(认领与生成(成员们, 页们))

    提醒保全(活动列表)
    return 活动列表
