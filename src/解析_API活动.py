# PRTS 的"活动开始/结束时间"存的是 UTC，比国服早 8 小时；
# cn 后缀属性是国服时间，但只有开始时间有，结束时间一律自己 +8h 换算
UTC国服差 = timedelta(hours=8)

日常窗口天 = 7
"""日常扫描窗口：**进行中的活动** + **结束时间在最近 7 天内**的已结束活动。

7 天与 CSV 的过期保留期（`身份CSV存储.过期保留天数 = 7`）对齐：扫更老的活动
也写不进 CSV（会被过期线清掉），只是白读公告。停机超过 7 天时，那段时间内结束的
活动不会再补；图上本来就只看近期窗口，影响只是"刚过去的那几天"，需要时用初始化重建。
"""

初始化窗口天 = 180
"""初始化（`回溯已结束=True`）的扫描窗口：最近半年。

用途是让"进行中/近期活动"能读到它挂在较早公告页上的原文（认领锚点、阶段与兑换窗口），
不再无差别扫全站历史。重建落盘仍只保留有效期内的条目，所以更老的结果只帮解析、不占数据。
"""


def 扫描窗口天(回溯已结束: bool) -> int:
    """本次扫描往后看多少天（初始化半年 / 日常 7 天）。"""
    return 初始化窗口天 if 回溯已结束 else 日常窗口天


def 在扫描窗口内(结束: str, 现在字符串: str, 回溯已结束: bool) -> bool:
    """已结束的活动是否仍在扫描范围内（进行中的不调用本函数）。"""
    现在dt = datetime.strptime(现在字符串, "%Y-%m-%d %H:%M:%S")
    窗口线 = (现在dt - timedelta(days=扫描窗口天(回溯已结束))).strftime("%Y-%m-%d %H:%M:%S")
    return 结束 >= 窗口线

