"""解析层 — 把 SMW ask 的查询结果转成活动条目

**公告是唯一时间源，ask 只当电话簿**（2026-09-17 定；页面名/类型/粗窗口/分组）：
wiki 手填的 SMW 属性会抄错（实测 `稳态测定` 的窗口被抄成月行水上那批的），
而公告原文是运营公告的逐字转载。ask 时间只剩三个用途：扫描窗口过滤（日常 7 天 /
初始化半年）、公告年份锚、无公告页条目（99 型常驻）的兜底。

认领顺序即降级顺序（`认领与生成`）：`公告=` 的 #板块锚点（wiki 的显式指认）→
板块标题含活动名 → （无公告页时）ask 粗窗口。**组里有公告页的，认不到段落就不生成**
——它的窗口由公告板块自生成的条目代表（2026-09-27 定：此前 ask 兜底会与板块自生成
条目同窗双行，矢量突破/03 在公告里叫「矢量突破#3「拟生态」」就是这么重复的）。
无人认领的板块（关卡◆/组合包/剿灭追加）照常自生成。
"""

