def 分类事件(API类型: str = "", 事件名: str = "") -> int:
    if API类型 and API类型 in API类型映射:
        return API类型映射[API类型]
    for 关键词列表, 类型 in 名称类型规则:
        for kw in 关键词列表:
            if kw in 事件名:
                return 类型
    return 1


def 长期显示名(api类型: str, 事件名: str) -> str | None:
    """长期条目的显示名 `官方名「对象名」`（卫戍协议·规程 → 卫戍协议「规程」）；
    页面名自带玩法名时剥掉、对象名用「」包（与官方 SideStory「XXX」同构）。
    非长期返回 None。"""
    官方名 = 长期活动.识别(api类型)
    if not 官方名:
        return None
    剥后 = re.sub(rf"^{re.escape(官方名)}[·：:\s]+", "", 事件名)
    if not 剥后:
        return 事件名
    return f"{官方名}「{剥后}」"


def 解析API时间戳(ts_info) -> str | None:
    """把 SMW 的 raw 时间转成 'YYYY-MM-DD HH:MM:00'

    raw 形如 1/2026/9/4/12/0/0，首段是日历标识（格里高利历=1）；
    兼容缺少首段的 6 段写法。
    """
    if isinstance(ts_info, dict):
        parts = ts_info.get("raw", "").split("/")
        if len(parts) >= 7:
            _, y, m, d, h, mi = parts[:6]
        elif len(parts) >= 6:
            y, m, d, h, mi = parts[:5]
        else:
            return None
        return f"{y}-{m.zfill(2)}-{d.zfill(2)} {h.zfill(2)}:{mi.zfill(2)}:00"
    return None


def 提取API时间(属性: dict, 键: str) -> str | None:
    值 = 属性.get(键)
    return 解析API时间戳(值[0]) if 值 else None


def 转国服时间(时间串: str | None) -> str | None:
    if not 时间串:
        return None
    t = datetime.strptime(时间串, "%Y-%m-%d %H:%M:%S") + UTC国服差
    return t.strftime("%Y-%m-%d %H:%M:%S")


def 提取官网链接(属性: dict) -> str:
    """官网公告标识：同一官方公告的活动（如月行水上和它的登录活动此夜同行）
    共享一个链接 id。无则返回空串。"""
    值 = 属性.get("官网链接")
    if not 值:
        return ""
    v = 值[0]
    return str(v.get("raw", "")).strip() if isinstance(v, dict) else str(v).strip()


def 是网页活动(属性: dict) -> bool:
    """挂 分类:网页活动 的是浏览器/H5 页面（冻土与火种这类抽奖/召回页），
    不是游戏内排期——不上图（2026-10-28 用户定）。"""
    return any("网页活动" in c.get("fulltext", "") for c in 属性.get("分类", []))


def 认领与生成(成员们: list[dict], 页们: dict[str, list[板块]]) -> list[dict]:
    """组内的三层认领与条目生成（**纯函数**：网络与页面定位由调用方负责，测试直接喂字典）。

    成员字段：事件名 / 显示名 / 开始 / 结束 / 类型 / 已结束 / 公告页 / 锚点。
    每个成员至多认领一个板块，每个板块至多被一个成员认领。
    """
    全板块 = [(页名, b) for 页名, 表 in 页们.items() for b in 表]
    判定 = 判定公告认领(成员们, 全板块)
    认领, 已领 = 判定.认领, 判定.已领
    已结束名们 = {m.get('显示名') for m in 成员们 if m.get('已结束')}
    已结束名们 |= {m.get('事件名') for m in 成员们 if m.get('已结束')}
    for 诊断 in 判定.诊断:
        # 整组已结束（初始化回溯会扫到很多老活动）：诊断降为 debug，不刷终端。
        # 「显式锚点零匹配、唯一标题兜底」是良性回退（解析结果仍来自公告），也降为 debug。
        良性 = '显式锚点零匹配；采用唯一标题兜底' in 诊断
        已结束 = any(n and n in 诊断 for n in 已结束名们)
        (logger.debug if 良性 or 已结束 else logger.warning)("公告认领：%s", 诊断)

    争议块 = set()
    无时间块 = set()
    for m in 成员们:
        if id(m) not in 判定.争议成员 | 判定.无时间成员:
            continue
        显式 = {i for i, (p, b) in enumerate(全板块)
              if m.get('锚点') and p == m.get('公告页') and b.标题 == m['锚点']}
        块集合 = 显式 or {i for i, (p, b) in enumerate(全板块)
                   if m.get('事件名') and m['事件名'] in b.标题
                   and (not m.get('公告页') or p == m['公告页'])}
        (争议块 if id(m) in 判定.争议成员 else 无时间块).update(块集合)
    # 板块索引仅协调本次认领；输出保留来源坐标，不将索引当持久身份。
    # 不同板块即使类型、窗口相同，也不能据此认定是同一个事件。
    结果 = []
    隔离来源, 更新问题, 保留来源父名 = set(), set(), set()
    块输出起点 = {}
    def 隔离(i, 原因):
        页名, b = 全板块[i]
        隔离来源.add((页名, b.标题))
        if i in 块输出起点:
            del 结果[块输出起点[i]:]
        父 = 页父名(页名)
        # 初始化会回溯半年，扫到早已结束的老公告：解析失败不该当成"这次没更新"报给用户
        # （它们的条目早已过期，进不了数据）。只有公告页的父活动还"进行中"才值得警告。
        父事件 = next((m for m in 成员们
                    if m.get('事件名') and (m['事件名'] == 父 or 父 in m['事件名'])), None)
        页成员 = [m for m in 成员们 if m.get('公告页') == 页名]
        if ((父事件 is not None and 父事件.get('已结束'))
                or (页成员 and all(m.get('已结束') for m in 页成员))):
            logger.debug("已结束公告页的隔离不报更新问题：%s / %s（%s）", 页名, b.标题, 原因)
            return
        保留来源父名.add(父)
        更新问题.add(f'公告页「{页名}」板块「{b.标题}」：{原因}，已局部隔离')

    for i, (页名, b) in enumerate(全板块):
        if i in 争议块 or i in 无时间块:
            隔离(i, '认领身份争议' if i in 争议块 else '无公告时间接管条件，不生成且禁止ask兜底')
            continue
        if sum(p == 页名 and other.标题 == b.标题 for p, other in 全板块) > 1:
            隔离(i, '重复来源标题，身份待确认')
            continue
        父名 = 页父名(页名)
        块输出起点[i] = len(结果)
        def 收集(条目们):
            if (页名, b.标题) in 隔离来源:
                return
            条目们 = list(条目们)
            if not 条目们 and (b.窗口 is None or (b.局部识别 is not None and 局部时间条目(b, 父名) is not None)):
                隔离(i, '时间不完整或时间选用为空，不生成且禁止ask兜底')
                return
            块输出 = []
            for 条目 in 条目们:
                if not 条目.get('结束时间'):
                    # 公告只给开启时刻（赛季常驻长期玩法，如卫戍协议）：结束用 API 窗口占位。
                    if not m:
                        隔离(i, '长期板块只有开始时刻，且没有 API 窗口可占位')
                        return
                    条目 = dict(条目, 结束时间=m['结束'],
                              时间角色=条目.get('时间角色') or '长期开放')
                if (条目['类型'] in {0, -1, 长期活动.类型值}
                        and not 条目.get('时间角色') and '_局部身份依据' not in 条目):
                    条目 = dict(条目, _来源板块=(页名, b.标题))
                    if 条目['类型'] == 0:
                        条目['_卡池来源'] = '公告'
                    块输出.append(条目)
                    continue
                条目 = 附加来源身份(条目, 页名, b.标题)
                if 条目.get('_原角色'):
                    条目['_活动关联'] = json.dumps(['公告活动关联-v1', 页名, b.标题],
                                               ensure_ascii=False, separators=(',', ':'))
                块输出.append(条目)
            keys = [a['_运行时身份'] for a in 块输出 if a.get('_运行时身份')]
            if len(keys) != len(set(keys)):
                隔离(i, '同源运行时身份重复')
            elif any('待确认' in a.get('_身份状态', '') or a.get('_身份问题') for a in 块输出):
                隔离(i, '来源或阶段身份待确认')
            else:
                结果.extend(块输出)
        m = 认领.get(i)
        if m is None:
            收集(板块条目(b, 父名))
            continue
        新条目 = 局部时间条目(b, 父名, m["显示名"], m["类型"])
        if 新条目 is not None:
            收集(新条目)
            continue
        阶段条 = 招募阶段条目(b, 父名, m["显示名"])
        if 阶段条 is not None:
            for 条目 in 阶段条:
                条目['_局部身份依据'] = None
            收集(阶段条)
            continue
        if b.类型 == 长期活动.类型值 and b.窗口 and not b.窗口[1]:
            # 只有开启时刻的长期板块（赛季常驻）：名字要带公告里的赛季号（罗马数字原样），
            # 不能用 API 事件名（那是"卫戍协议·规程"，丢了「序列I」）。
            命名条 = 板块条目(b, 父名)
            if 命名条:
                for 条目 in 命名条:
                    条目['_原角色'] = 条目['时间角色']    # 让收集层补活动关联
                收集(命名条)
                continue
        收集([{"名称": m["显示名"], "开始时间": b.窗口[0], "结束时间": b.窗口[1],
                     "类型": m["类型"], "_parent": 父名}])
        if 关卡 := 关卡条目(b, 父名):
            关卡['_局部身份依据'] = None
            收集([关卡])

    for m in 成员们:                                 # ③ 无公告页 → ask 粗窗口兜底
        if id(m) in 已领 or id(m) in 判定.争议成员 | 判定.无时间成员:
            continue
        if 页们 and m["类型"] != 长期活动.类型值:
            # 组里有公告页：公告是唯一时间源，认不到段落就不生成（2026-09-27 定，
            # 起因：矢量突破/03 在公告里叫「矢量突破#3「拟生态」」，字面对不上号 →
            # ask 兜底又生成一条，和板块自生成的「拟生态」同窗双行）。
            # 它的窗口由公告板块自生成的条目代表；名字土一点没关系，出自公告就行。
            # 长期（99）例外（2026-10-28 卫戍协议）：常驻的窗口就该用 ask 整段
            # 时间，而它的板块抽不出对象名（见 解析_公告._长期任务名）不会自生成，
            # 压制它条目就没了。
            logger.debug("  %s → 公告未认领，不生成（由板块自生成条目代表）", m["显示名"])
            continue
        if m["已结束"]:
            logger.debug("  %s → 未认领（已结束，不添加）", m["显示名"])
        else:
            条目 = {"名称": m["显示名"], "开始时间": m["开始"], "结束时间": m["结束"],
                  "类型": m["类型"], "_parent": ""}
            if m['类型'] not in {0, -1, 长期活动.类型值}:
                来源页 = m.get('API来源页') or m.get('事件名')
                if isinstance(来源页, str) and 来源页.strip():
                    条目['_API来源页'] = 来源页
                    条目['_运行时身份'] = json.dumps(
                        ['PRTS事件页-v1', 'prts.wiki', 来源页], ensure_ascii=False, separators=(',', ':'))
                    条目['_身份状态'] = 'API页范围可对应'
                else:
                    条目['_身份状态'] = 'API来源身份待确认'
            结果.append(条目)
            logger.debug("  %s → ask 时间（类型 %s，无公告页兜底）", m["显示名"], m["类型"])
    全局问题 = tuple(a.get('_身份问题') or 'API来源身份待确认' for a in 结果 if '待确认' in a.get('_身份状态', '') or a.get('_身份问题'))
    return 公告条目批次(结果, 全局问题, 隔离来源=sorted(隔离来源),
                      更新问题=sorted(更新问题), 保留来源父名=sorted(保留来源父名))


def API转活动列表(api原始: list[dict], 现在时间: str, 回溯已结束: bool = False) -> list[dict]:
    """SMW ask 结果 → 活动条目列表（机制见模块 docstring）

    - `回溯已结束=False`（日常）：只看**进行中 + 最近 7 天内结束过**的活动；
    - `回溯已结束=True`（初始化：CLI `--bootstrap` / `/方舟日程 初始化`）：最近**半年**。

    公告页会被**追加**内容（新的剿灭轮换写在当期活动的公告里），所以看得到的组
    每次都重读公告——公告也是我们唯一的显示时间来源。

    新增与过期不在这里判断：交给下游 `合并保存CSV`（它拿这个列表和昨天的 CSV 合并，
    有新增就加、过期就删）。
    """
    # 整理成员：ask 只提供身份（名称/类型/分组）与粗窗口（过滤 + 年份锚）
    待处理: list[dict] = []
    for 事件名, 条目 in api原始:
        属性 = 条目.get("printouts", {})
        if 是网页活动(属性):
            logger.debug("  %s → 网页活动（浏览器/H5 页面），不上图", 事件名)
            continue
        开始 = 提取API时间(属性, "活动开始时间cn") or 转国服时间(提取API时间(属性, "活动开始时间"))
        结束 = 转国服时间(提取API时间(属性, "活动结束时间"))
        if not (开始 and 结束):
            continue
        已结束 = 结束 <= 现在时间
        if 已结束 and not 在扫描窗口内(结束, 现在时间, 回溯已结束):
            continue
        api类型 = (属性.get("活动类型") or [None])[0] or ""
        # 长期玩法用官方名当前缀（左列只写「长期」，玩法信息得靠名字带）；
        # 前缀与识别来自 src/长期活动.py —— 剿灭/保全 也一起走，不再只挑肉鸽/联动
        if (长期名 := 长期显示名(api类型, 事件名)):
            显示名 = 长期名
        elif api类型 == "合作活动":
            显示名 = f"联动「{事件名}」"
        else:
            显示名 = 事件名
        开始dt = datetime.strptime(开始, "%Y-%m-%d %H:%M:%S")
        结束dt = datetime.strptime(结束, "%Y-%m-%d %H:%M:%S")
        待处理.append({
            "事件名": 事件名,
            "API来源页": 条目.get('fulltext') or 事件名,
            "显示名": 显示名,
            "开始": 开始,
            "结束": 结束,
            "类型": 分类事件(API类型=api类型 or "", 事件名=事件名),
            "api类型": api类型,
            "已结束": 已结束,
            "组": 提取官网链接(属性) or 显示名,
            # 公告里多数只写"X月X日"：定年份要拿**父活动的时间窗中点**当基准
            # （用"今天"当基准会把老公告算成今年，见 解析_公告.解析时间）
            "参考": 开始dt + (结束dt - 开始dt) / 2,
        })

    # 逐成员读活动页本体的 {{活动信息}}，拿 公告= 指认（长期常驻没有公告页，跳过）
    for m in 待处理:
        m["公告页"] = m["锚点"] = None
        m["本体文本"] = None
        if m["类型"] != 长期活动.类型值:
            文本 = 获取页面wikitext(m["事件名"])
            m["本体文本"] = 文本
            信息 = 解析活动信息(文本 or "")
            if 信息.get("公告"):
                m["公告页"], m["锚点"] = 公告定位(信息["公告"])
            elif 定位 := 引用公告定位(文本 or ""):
                m["公告页"], m["锚点"] = 定位
            # 支线故事的官方全名带 SideStory 前缀（名称=SideStory「时间啊，向前！」），
            # 页面名/名称缩短都把它丢了——图上直接用官方全名，前缀形态
            # （裸前缀 + 「」包名）正是统一的样式（2026-10-29 定）
            if m["api类型"] == "支线故事" and 信息.get("名称"):
                m["显示名"] = 信息["名称"]

    分组: dict[str, list[dict]] = {}
    for t in 待处理:
        分组.setdefault(t["组"], []).append(t)

    公告缓存: dict[tuple[str, datetime, bool], list[板块]] = {}

    def 取公告(页名: str, 参考: datetime, 静默: bool = False) -> list[板块]:
        """读一份公告页 → 板块表；读不到 → 空表。缓存键带**参考窗**：
        同一份公告可能被复刻页指回，年份锚不同则解析结果不同，不能共用。
        `静默` 只影响日志级别（页面所属活动已结束 → 诊断写 debug）。"""
        键 = (页名, 参考, 静默)
        if 键 not in 公告缓存:
            wikitext = 获取页面wikitext(页名)
            公告缓存[键] = 抽板块(wikitext, 参考, 静默=静默) if wikitext else []
        return 公告缓存[键]

    活动列表 = 公告条目批次()
    for 成员们 in 分组.values():
        # 长期排最后（2026-10-28 卫戍协议改赛季常驻后归入长期）：它的窗口整年，
        # 不该由它当主成员——默认公告页取它的、共享公告的年份锚取它的中点，
        # 都会把短活动的日期带偏一年
        成员们.sort(key=lambda m: (m["类型"] == 长期活动.类型值, m["类型"] == 2, m["已结束"]))
        # 整组都结束了（初始化回溯半年会扫到很多）：这一组的解析诊断降为 debug
        组静默 = all(m["已结束"] for m in 成员们)
        # 组的公告页：成员 公告= 指的页；没人写过才退回主成员的默认公告页
        候选们 = [m["公告页"] for m in 成员们 if m["公告页"]]
        if not 候选们 and 成员们[0]["类型"] != 长期活动.类型值:
            候选们 = [公告页标题(成员们[0]["事件名"])]
        页们 = {页: 表 for 页 in dict.fromkeys(候选们)
               if (表 := 取公告(页, 成员们[0]["参考"], 组静默))}
        if not 页们 and (本体 := 成员们[0]["本体文本"]):
            # 公告页全落空时，试**活动页本体**——有的活动把整份公告直接写在
            # 页面自己的章节里（恒远津梁：{{活动信息}} 没写 公告=、
            # `X/活动公告` 子页也没建，公告就是页面正文的 == 章节）。
            # 文本在上一循环已读过，这里零新增请求；也只在别的全失败时兜底
            # （正常组不会把活动页的游戏说明章节误当公告）
            if (表 := 抽板块(本体, 成员们[0]["参考"], 静默=组静默)):
                页们 = {成员们[0]["事件名"]: 表}
        批次 = 认领与生成(成员们, 页们)
        活动列表.合并批次(批次)

    # 同一公告来源可能被不同API分组重读；任一组隔离后不能由另一组回灌。
    隔离集合 = set(活动列表.隔离来源)
    活动列表[:] = [a for a in 活动列表 if a.get('_来源板块') not in 隔离集合]
    提醒保全(活动列表)
    return 活动列表
