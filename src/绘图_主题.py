"""配色：一个种子主色 → 副色 → 警告色（色相先行，明度由对比距离推导）

三层结构，每层的来源分得很清楚：

一、色相层（从图里取，只回答"这张图是什么颜色"）
    主色：32×32 降采样 + 16 档分桶 + 跳过半透明像素，按 `频率占比 × 饱和度²` 取最高分
          （MAA ColorExtractorHelper 的做法：饱和度平方保证鲜艳色优先）。
    副色：在色相距离 ≥ 30° 的候选里按 `色相距离×0.65 + 鲜艳度×0.25 + 占比×0.10` 取最高
          （astrbot_plugin_palette 的做法：权重压在色相距离上）。
    警告色：由主色与副色算出——两色把色相环切成两段弧，取较长弧的中点，
          与两者等距且最远。

二、饱和度层（固定档位，不随图片变化）
    主色系 0.115 / 大色块 0.060 / 背景体系 0.020 / 文字 0.008（Oklab 彩度）
    取自 MAA MonetPaletteHelper：饱和度按角色固定，才能任何图都保持同一套观感，
    不会因为图偏灰就发闷、图偏艳就刺眼。

三、亮度层（由对比距离推导，不查表）
    深底 0.16 / 更深 0.10 / 面板 0.96 是锚点；文字 = 底色 ± 对比距离：
        深底正文 = 深底 + 0.80、次级 + 0.56、弱化 + 0.40
        浅底正文 = 面板 − 0.78、次级 − 0.46、弱化 − 0.32
    这也是 MAA 的思路：明度是"要拉开多少对比"算出来的结果，而不是拍脑袋定的档位。

分类色不另造色相：以主色相为**中心**、左右各 40°（总跨 80°）采一段邻近色，同时叠一条由浅到深的明度梯度，
两个维度一起做连续过渡，于是低彩（莫兰迪）下也能分辨类别。警告色只服务"今天"这一个语义角色。
"""

from __future__ import annotations

import logging
import math
from dataclasses import dataclass

import numpy as np
from PIL import Image as PILimage

from .绘图_颜色 import _oklab_to_srgb, _srgb_to_oklab

logger = logging.getLogger(__name__)

缺省色相 = 205.0
分桶步长 = 16               # RGB 每 16 一档分桶（MAA 的 BucketSize）
降采样 = 32                 # 取色前先缩到 32×32（MAA 的 SampleSize）
副色最小间距 = 40.0         # 副色要与主色差这么多，才算是"另一个色相峰"
副色偏移 = 35.0             # 图片过于单色时的兜底偏移
彩度地板 = 0.05             # 近中性色的"色相"没有意义，不参与定主色
色弧全宽 = 80.0             # 分类色弧的总跨度（度）
色弧_主色位置 = 1 - 0.618   # 主色相落在弧上的位置：0 = 起点、0.5 = 正中、1 = 终点
"""主色相在分类色弧上的落点（黄金分割的反侧，约 0.382）。

朝副色那一侧留得更长（保留"主 → 副"的方向感），反侧只占剩下的一小段。
既不在端点（不会被某一个类型独占）也不在正中（两端余量不平均，画面更均衡）。
"""
对比下限 = 4.5              # WCAG AA

# —— 第二层：饱和度固定档（Oklab 彩度 C）——
# 整体压低彩度往莫兰迪（浊色）方向靠：大面积更浊，文字近乎中性
C_主色系 = 0.070
C_大色块 = 0.042
C_面板染色 = 0.022        # 面板底的色温：大面积承色，比 4px 色条更容易被看见
C_背景体系 = 0.012
C_文字 = 0.006

# —— 第三层：亮度锚点与对比距离 ——
L_深底 = 0.22            # 柔和深灰，不用近黑
L_更深 = 0.16
L_面板 = 0.95
L_条浅 = 0.86            # 时间条的明度梯度：浅 → 深
L_条深 = 0.66
对比_正文 = 0.74
对比_次级 = 0.50
对比_弱化 = 0.34
L_强调 = 0.72
L_小色块 = 0.62


def _造色(色相度: float, L: float, C: float) -> str:
    h = math.radians(色相度)
    rgb = _oklab_to_srgb(np.array([[L, C * math.cos(h), C * math.sin(h)]]))[0]
    r, g, b = (int(round(float(np.clip(v, 0.0, 1.0)) * 255)) for v in rgb)
    return f"#{r:02x}{g:02x}{b:02x}"


def 相对亮度(色: str) -> float:
    def _线性(c: float) -> float:
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (int(色[i:i + 2], 16) / 255 for i in (1, 3, 5))
    return 0.2126 * _线性(r) + 0.7152 * _线性(g) + 0.0722 * _线性(b)


def 对比度(前景: str, 背景: str) -> float:
    a, b = 相对亮度(前景), 相对亮度(背景)
    亮, 暗 = max(a, b), min(a, b)
    return (亮 + 0.05) / (暗 + 0.05)


def _色相距(a: float, b: float) -> float:
    差 = abs(a - b) % 360
    return min(差, 360 - 差)


def 取候选色(背景路径: str | None) -> list[tuple[float, float, float, float]]:
    """分桶统计图片颜色 → [(色相, 彩度, 明度, 分数)]，分数 = 频率占比 × 饱和度²"""
    if not 背景路径:
        return []
    try:
        图 = PILimage.open(背景路径).convert("RGB")
    except Exception:
        logger.warning("无法读取背景图，配色回退到中性色相: %s", 背景路径)
        return []
    图.thumbnail((降采样 * 4, 降采样 * 4))
    arr = np.asarray(图, dtype=np.float64).reshape(-1, 3)

    桶: dict[int, list] = {}
    for r, g, b in arr:
        key = (int(r) // 分桶步长 * 64 + int(g) // 分桶步长) * 64 + int(b) // 分桶步长
        项 = 桶.get(key)
        if 项 is None:
            桶[key] = [1, r, g, b]
        else:
            项[0] += 1
            项[1] += r
            项[2] += g
            项[3] += b

    总数 = len(arr) or 1
    lab = _srgb_to_oklab(
        np.array([[项[1] / 项[0] / 255, 项[2] / 项[0] / 255, 项[3] / 项[0] / 255]
                  for 项 in 桶.values()]))
    候选 = []
    for 项, (L, a, b) in zip(桶.values(), lab):
        占比 = 项[0] / 总数
        L, C = float(L), float(math.hypot(a, b))
        if L < 0.06 or L > 0.95:            # 纯黑纯白不参与
            continue
        分数 = 占比 * min(C / 0.15, 1.0) ** 2      # 频率 × 饱和度²
        候选.append((math.degrees(math.atan2(b, a)) % 360, C, L, 分数))
    候选.sort(key=lambda t: -t[3])
    # 彩度地板：近中性色往往是"把画面各色搅匀后的搅拌色"（实测两张样例图的
    # 头名彩度只有 0.031/0.032），它的色相在数学上就是噪声，不能用来定义整套配色。
    # 全部候选都不够彩时才退让，并按彩度取最大者，避免跳到与图片无关的兜底色相。
    够彩 = [c for c in 候选 if c[1] >= 彩度地板]
    return 够彩 or sorted(候选, key=lambda c: -c[1])


def 取三色(背景路径: str | None) -> tuple[float, float, float, float]:
    """返回 (主色相, 副色相, 警告色相, 主色明度)"""
    候选 = 取候选色(背景路径)
    if not 候选:
        return 缺省色相, (缺省色相 + 90) % 360, (缺省色相 + 180) % 360, 0.5

    主 = 候选[0]
    主色相, 主L = 主[0], 主[2]

    # 副色同样从图里取，但必须是"另一个色相峰"：色相距离不足 40° 的都算同一个峰，
    # 取它只会让主副色变成同一种颜色（实测某样例图副色只差 16.8°，强调色几乎重合）
    备选 = [c for c in 候选 if _色相距(c[0], 主色相) >= 副色最小间距]
    副色相 = 备选[0][0] if 备选 else (主色相 + 副色偏移) % 360

    return 主色相, 副色相, _长弧中点(主色相, 副色相), 主L


def _长弧中点(甲: float, 乙: float) -> float:
    """两色相把色相环切成两段弧，取较长弧的中点（与两者等距且最远）"""
    return ((甲 + 乙) / 2 + (180.0 if _色相距(甲, 乙) < 180.0 else 0.0)) % 360


@dataclass(frozen=True)
class 主题:
    主色相: float
    副色相: float
    警告色相: float
    主色明度: float
    弧起: float = 缺省色相
    弧长: float = 副色偏移
    深底: str = "#1a1c1e"
    更深: str = "#121415"
    面板: str = "#f4f5f5"
    主文: str = "#f4f5f6"
    次文: str = "#bcbfc1"
    微文: str = "#8a8e91"
    面板题: str = "#2b2f32"
    面板次文: str = "#5f6467"
    面板微文: str = "#7c8286"
    强调: str = "#7fb3d5"
    副强调: str = "#a9a2d8"
    今天: str = "#e0a35f"
    网格: str = "#3b3e41"
    分隔: str = "#303336"
    描边: str = "#d7d9da"

    # —— 色相层：沿主色弧采样，t ∈ [0,1] ——
    def 色相(self, t: float) -> float:
        return (self.弧起 + self.弧长 * min(max(t, 0.0), 1.0)) % 360

    # —— 明度层：由对比距离决定 ——
    def 大色块(self, t: float) -> str:
        """大面积（时间条）：色相沿弧走、明度同时由浅到深。
        两个维度一起做梯度，低彩下也能分辨类别，且整体是连续的浊色渐变"""
        k = min(max(t, 0.0), 1.0)
        return _造色(self.色相(k), L_条浅 + (L_条深 - L_条浅) * k, C_大色块)

    def 标题色(self, t: float, 亮度: float) -> str:
        """底栏卡片的标题带色：与时间条**同一个彩度家族**（莫兰迪浊色），只是可以更浅/更深。

        对比过"深而艳实带 + 反白字"那版：一整块高彩度从整体"浅而浊"的调子里跳出来太扎眼。
        现在由调用方给 `亮度`（0.80 左右 = 淡带 + 本区深色标题字）。
        """
        return _造色(self.色相(t), 亮度, C_大色块)

    def 小色块(self, t: float) -> str:
        """小面积（徽标、顶部色条、行首色条）：同族浊色，配白字，明度按对比度下探"""
        h = self.色相(t)
        L = L_小色块
        while L > 0.30:
            色 = _造色(h, L, C_主色系)
            if 对比度(色, self.主文) >= 对比下限:
                return 色
            L -= 0.04
        return _造色(h, L, C_主色系)

    def 对色(self, 底色: str) -> str:
        return (self.主文 if 对比度(self.主文, 底色) >= 对比度(self.面板题, 底色)
                else self.面板题)

    def 面板底(self, t: float) -> str:
        """分区面板的底色：不是纯白，而是带本区色温的近白。
        大面积承色——同一档色差放在整块面板上，比放在 4px 色条上更容易被看见，
        缩放后也不会丢（色条在手机上只有不到 1px）"""
        return _造色(self.色相(t), L_面板 - 0.01, C_面板染色)

    def 面板标题色(self, t: float) -> str:
        """分区名用本区的深色调，让"这一区是什么色"由文字再确认一次"""
        return _造色(self.色相(t), L_面板 - 0.62, C_主色系 * 1.1)

    def 面板描边(self, t: float) -> str:
        """面板标题下的细分隔线：同色相的淡一档"""
        return _造色(self.色相(t), L_面板 - 0.13, C_面板染色)

    def 描边RGB(self) -> tuple[int, int, int, int]:
        r, g, b = (int(self.描边[i:i + 2], 16) for i in (1, 3, 5))
        return r, g, b, 255


def _建主题_计算(背景路径: str | None = None) -> 主题:
    主色相, 副色相, 警告色相, 主L = 取三色(背景路径)

    # 分类色弧：总跨 色弧全宽，主色相落在弧的 `色弧_主色位置` 处——
    # 朝副色那一侧更长（保留"主 → 副"的方向感），反侧只占剩下的一小段。
    # 方向取主副色之间的短弧那一侧，不会走反
    方向 = 1.0 if (副色相 - 主色相) % 360 <= 180 else -1.0
    弧长 = 色弧全宽 * 方向
    弧起 = (主色相 - 色弧全宽 * 色弧_主色位置 * 方向) % 360

    def 深底文(距离: float) -> str:
        return _造色(主色相, min(L_深底 + 距离, 0.97), C_文字)

    def 浅底文(距离: float) -> str:
        return _造色(主色相, max(L_面板 - 距离, 0.06), C_文字)

    return 主题(
        主色相=主色相, 副色相=副色相, 警告色相=警告色相, 主色明度=主L,
        弧起=弧起, 弧长=弧长,
        深底=_造色(主色相, L_深底, C_背景体系),
        更深=_造色(主色相, L_更深, C_背景体系),
        面板=_造色(主色相, L_面板, C_背景体系 * 0.5),
        主文=深底文(对比_正文), 次文=深底文(对比_次级), 微文=深底文(对比_弱化),
        面板题=浅底文(0.72), 面板次文=浅底文(0.42), 面板微文=浅底文(0.28),
        强调=_造色(主色相, L_强调, C_主色系),
        副强调=_造色(副色相, L_强调, C_主色系),
        今天=_造色(警告色相, L_强调, C_主色系),
        网格=_造色(主色相, L_深底 + 0.10, C_背景体系),
        分隔=_造色(主色相, L_深底 + 0.06, C_背景体系),
        描边=_造色(主色相, L_面板 - 0.10, C_背景体系),
    )


def 建主题(背景路径: str | None = None) -> 主题:
    """背景图 → 整套配色。

    整套色值完全由这一张图推导（`取候选色` 是纯 Python 的逐像素分桶，实测约 87ms）。

    > 阶段四曾在这里按"路径 + mtime + 大小"缓存过（省 ~87ms）。2026-09-14 拿掉了：
    > 一次出图只建一次主题，87ms 相对整张图的绘制时间可以忽略，
    > 不值得换一层"指纹忘了更新就会一直用旧配色"的缓存键（理由同 `绘图_图表.py`）。
    """
    return _建主题_计算(背景路径 or None)
