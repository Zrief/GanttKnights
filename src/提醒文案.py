"""提醒文案 —— 节点提醒里**所有给人看的字**都在这里（改措辞只改这个文件）。

## 为什么单独拆出来

`生成_提醒.py` 管的是**判据**：哪些活动在节点上、怎么排序、最多列几行。
而这个文件管的是**表达**：图标、`今天/明天/N 天后`、`…另有 N 项`。
两者混在一起时，想改一句"⚠️ 明天结束"得去判据文件里翻——读代码的人还会以为改的是逻辑。

提醒接口：`组头()` / `条目行()` / `省略行()` / `最多列几行`，以及
`共同结束名()` / `结束说明()`；节点判据与时间日偏移仍由生成层负责。
调用方（`生成_提醒.py`）只做拼装，不写字面量。

本文件还管**活动名怎么显示**：`展示名()`（图上用的裸名）与 `提醒名()`（提醒里带类型）。
它们是同一件事的两面——数据层的名字是三个解析器各拼各的，给人看之前要归一。

> 想大改文风的用户改这里；只想加句前缀/落款这类**个人偏好**的，走插件配置的
> 「推送文案模板」（那是配置项，不用改代码、也不用重载）。
"""

from __future__ import annotations

import re
from datetime import datetime

from . import 长期活动

类型图标: dict[int, str] = {0: "🎯", 1: "📅", 2: "🎁", -1: "🛒", 99: "📌"}
"""活动类型 → 图标（与 `src/活动.py` 的类型编号对应）。"""

缺省图标 = "📋"
"""类型不认识时用的图标。"""

最多列几行 = 10
"""一次提醒最多列几行事件（组头与"…另有 N 项"都不算）。首装/初始化后可能一次命中很多节点。"""

当天前缀 = "🔥 "
次日前缀 = "⚠️ "
"""紧急程度图标：当天 🔥、次日 ⚠️、更远什么都不带。"""


def 组头(偏移: int, 侧: str) -> str:
    """偏移 + 侧 → 分组那一行：`🔥 今天结束` / `⚠️ 明天结束` / `3 天后结束`。

    偏移就是"边界距今的天数"（0 = 今天、-1 = 明天、-3 = 三天后）；正数兜底成"N 天前"。
    """
    名字 = "结束" if 侧 == "结束" else "开启"
    if 偏移 == 0:
        return f"{当天前缀}今天{名字}"
    if 偏移 == -1:
        return f"{次日前缀}明天{名字}"
    return f"{-偏移} 天后{名字}" if 偏移 < 0 else f"{偏移} 天前{名字}"


def 条目行(名称: str, 类型: int) -> str:
    """一条活动 → 一行：`📅 活动名`。"""
    return f"{类型图标.get(类型, 缺省图标)} {名称}"


def 共同结束名(活动本名: str) -> str:
    """只有经判据层确认的关卡组才使用这个名称。"""
    return f"{活动本名}·活动关卡共同结束"


def 结束说明(结束: datetime, 偏移: int, *, 共同结束: bool = False) -> str:
    """不改日偏移：凌晨次日截止提示最后完整游玩日；共同节点注明精确时刻。"""
    if 偏移 == -1 and 结束.hour < 4:
        return f" (明天{结束:%H:%M}结束；今天是最后完整游玩日)"
    if 共同结束:
        return f" ({结束:%m-%d %H:%M}结束)"
    return ""


def 省略行(条数: int) -> str:
    """命中太多、被行数上限截掉时的最后一行。"""
    return f"…另有 {条数} 项"


# ============================ 活动名的展示规范 ============================

卡池前缀 = ("【标准池】", "【中坚池】", "【寻访】")
"""数据层给卡池拼的前缀（生产端只有这三种：`解析_卡池.分区规则` 与
`解析_公告.板块条目`）。展示时整段丢掉——类型已经由甘特图左列表达（`活动.子类型`）。"""

期号_RE = re.compile(r"^#\d+\s*·\s*")
甄选期号_RE = re.compile(r"^((?:定向|中坚|标准)甄选)\d*\s*·\s*")
"""卡池数字期号（`#193 · `）直接丢；甄选池的期号只丢数字、**保留池名**
（`中坚甄选07 · 圣聆初雪` → `中坚甄选 · 圣聆初雪`）。

甄选已经并入「限时」左列分组（2026-10-31），池名不再由左列表达——再连池名一起丢掉，
图上就只剩一串干员名，和联合行动/卫戍寻访的显示形态对不上。
"""

长期括号前缀_RE = re.compile(r"^[【「](?P<玩法>[^】」]+)[】」](?P<对象>.+)$")
长期裸前缀_RE = re.compile(r"^(?P<玩法>[^「」【】]+?)「(?P<对象>[^「」]+)」$")
"""拆开长期条目名字里的玩法段与对象段——历史上有三种写法：
`【剿灭】默祷圣祠`（旧数据）、`「剿灭」默祷圣祠`（2026-10-29 中间态）、
`剿灭作战「默祷圣祠」`（现行，前缀裸着、「」包对象）。"""

长期黑话 = {"肉鸽": "集成战略"}
"""「肉鸽」是黑话，PRTS 的 SMW 里没有这个词，只能硬写。"""


def _归一长期(名称: str) -> str | None:
    """长期条目的任意历史写法 → `官方名「对象」`（如 `剿灭作战「默祷圣祠」`）；
    认不出玩法的返回 None（调用方保持原样）——查表本身就是护栏，
    SideStory「XXX」/「联动」XXX 这类活动名不会被误改。"""
    m = 长期裸前缀_RE.match(名称) or 长期括号前缀_RE.match(名称)
    if not m:
        return None
    官方名 = 长期黑话.get(m["玩法"]) or 长期活动.官方名.get(m["玩法"])
    if not 官方名:
        return None
    return f"{官方名}「{m['对象']}」"

池名单最多直列 = 5
"""条内/推送里直列的 UP 干员数上限（2026-10-29 定 5：联合行动这类 4 人池
全列，卫戍寻访/甄选 10-12 人池直列会把甘特条撑到放不下）——超过就留
前几个 +「等 N 人」。只影响展示，数据层（CSV/身份键换岗）仍是全名单。"""


def _缩名单(名: str) -> str:
    """`池名 · A / B / C…` 的名单超过 池名单最多直列 人时留前几个 +「等 N 人」。

    认不出名单结构（没有 ` · ` 段）或人数不超的原样返回——
    `海渊巡游 · 克莱门莎`、`昨日海 · 关卡` 这类单对象名不受影响。
    """
    头, 分隔, 名单 = 名.rpartition(" · ")
    段 = 名单 if 分隔 else 名
    干员们 = [x.strip() for x in 段.split(" / ") if x.strip()]
    if len(干员们) <= 池名单最多直列:
        return 名
    return (f"{头}{分隔}" if 分隔 else "") +            f"{' / '.join(干员们[:池名单最多直列])} 等 {len(干员们)} 人"


附属后缀 = ("关卡", "礼包", "组合包", "时装")
"""活动的附属条目用 `空格 + 后缀` 命名，统一改写成 `· 后缀`（同卡池的 `· 干员`）。"""


def 展示名(名称: str) -> str:
    """图上显示的名字（**只影响显示，不改数据**）。

    数据层的名字来自三个地方、写法本来就不齐：

    - 卡池 —— `解析_卡池.分区规则` 拼出 `【标准池】#193 · 乌尔比安 / 仇白`；
    - 长期 —— `剿灭作战「默祷圣祠」`（现行，前缀裸着、「」包对象；历史写法归一到它）；
    - 活动 / 福利 —— 直接用 PRTS 活动页名（SideStory 用官方全名 `SideStory「XXX」`）。

    统一规则（2026-09-24 定；长期前缀形态 2026-10-29 定；甄选池名 2026-10-31 统一）：

    1. **卡池**：类型前缀与数字期号丢掉，**池名保留**（`【标准池】#193 · 乌尔比安 / 仇白`
       → `乌尔比安 / 仇白`；`【中坚池】中坚甄选07 · …` → `中坚甄选 · …`）——
       左列只表达大类（甄选已并入「限时」），池名得留在名字里，形态才和联合行动/卫戍寻访一致；
    2. **附属条目**：`空格 + 后缀` 改成 `· 后缀`，与卡池的 `· 干员` 用同一个分隔符；
    3. **长期**：任意历史写法归一成 `官方名「对象」`（`【肉鸽】X` → `集成战略「X」`）——
       左列不细分长期，玩法信息得在名字里；
    4. **活动 / 福利**：不加前缀，它们本身就没有细分。
    """
    名 = 名称.strip()
    for 旧 in 卡池前缀:
        if 名.startswith(旧):
            名 = 名[len(旧):]
            break
    名 = 期号_RE.sub("", 名)
    名 = 甄选期号_RE.sub(r"\1 · ", 名)
    名 = _缩名单(名)
    if (归一 := _归一长期(名)):
        名 = 归一
    for 尾 in 附属后缀:
        if 名.endswith(" " + 尾):
            return 名[: -len(尾) - 1] + " · " + 尾
    return 名


def 提醒名(名称: str, 子类型: str = "") -> str:
    """提醒里用的名字：**带类型**。

    推送与控制台没有甘特图左列，裸名会丢掉"这是哪个池子"——所以把 `活动.子类型`
    补回前缀。长期/活动/福利的名字里本来就带着类型（`「集成战略」…`），不再补。
    """
    名 = 展示名(名称)
    if 子类型 and not 名.startswith("【"):
        return f"【{子类型}】{名}"
    return 名
