"""提醒文案 —— 节点提醒里**所有给人看的字**都在这里（改措辞只改这个文件）。

## 为什么单独拆出来

`生成_提醒.py` 管的是**判据**：哪些活动在节点上、怎么排序、最多列几行。
而这个文件管的是**表达**：图标、`今天/明天/N 天后`、`…另有 N 项`。
两者混在一起时，想改一句"⚠️ 明天结束"得去判据文件里翻——读代码的人还会以为改的是逻辑。

对外只有四个名字：`组头()` / `条目行()` / `省略行()` / `最多列几行`。
调用方（`生成_提醒.py`）只做拼装，不写字面量。

> 想大改文风的用户改这里；只想加句前缀/落款这类**个人偏好**的，走插件配置的
> 「推送文案模板」（那是配置项，不用改代码、也不用重载）。
"""

from __future__ import annotations

类型图标: dict[int, str] = {0: "🎯", 1: "📅", 2: "🎁", -1: "🛒", 99: "📌"}
"""活动类型 → 图标（与 `src/活动.py` 的类型编号对应）。"""

缺省图标 = "📋"
"""类型不认识时用的图标。"""

最多列几行 = 10
"""一次提醒最多列几行事件（组头与"…另有 N 项"都不算）。首装/初始化后可能一次命中很多节点。"""

当天前缀 = "🔥 "
次日前缀 = "⚠️ "
"""紧急程度图标：当天 🔥、次日 ⚠️、更远什么都不带。"""


def 组头(偏移: int, 侧: str) -> str:
    """偏移 + 侧 → 分组那一行：`🔥 今天结束` / `⚠️ 明天结束` / `3 天后结束`。

    偏移就是"边界距今的天数"（0 = 今天、-1 = 明天、-3 = 三天后）；正数兜底成"N 天前"。
    """
    名字 = "结束" if 侧 == "结束" else "开启"
    if 偏移 == 0:
        return f"{当天前缀}今天{名字}"
    if 偏移 == -1:
        return f"{次日前缀}明天{名字}"
    return f"{-偏移} 天后{名字}" if 偏移 < 0 else f"{偏移} 天前{名字}"


def 条目行(名称: str, 类型: int) -> str:
    """一条活动 → 一行：`📅 活动名`。"""
    return f"{类型图标.get(类型, 缺省图标)} {名称}"


def 省略行(条数: int) -> str:
    """命中太多、被行数上限截掉时的最后一行。"""
    return f"…另有 {条数} 项"
