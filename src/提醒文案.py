"""提醒文案 —— 节点提醒里**所有给人看的字**都在这里（改措辞只改这个文件）。

## 为什么单独拆出来

`生成_提醒.py` 管的是**判据**：哪些活动在节点上、怎么排序、最多列几行。
而这个文件管的是**表达**：图标、`今天/明天/N 天后`、`…另有 N 项`。
两者混在一起时，想改一句"⚠️ 明天结束"得去判据文件里翻——读代码的人还会以为改的是逻辑。

提醒这一侧对外只有四个名字：`组头()` / `条目行()` / `省略行()` / `最多列几行`。
调用方（`生成_提醒.py`）只做拼装，不写字面量。

本文件还管**活动名怎么显示**：`展示名()`（图上用的裸名）与 `提醒名()`（提醒里带类型）。
它们是同一件事的两面——数据层的名字是三个解析器各拼各的，给人看之前要归一。

> 想大改文风的用户改这里；只想加句前缀/落款这类**个人偏好**的，走插件配置的
> 「推送文案模板」（那是配置项，不用改代码、也不用重载）。
"""

from __future__ import annotations

import re

from . import 长期活动

类型图标: dict[int, str] = {0: "🎯", 1: "📅", 2: "🎁", -1: "🛒", 99: "📌"}
"""活动类型 → 图标（与 `src/活动.py` 的类型编号对应）。"""

缺省图标 = "📋"
"""类型不认识时用的图标。"""

最多列几行 = 10
"""一次提醒最多列几行事件（组头与"…另有 N 项"都不算）。首装/初始化后可能一次命中很多节点。"""

当天前缀 = "🔥 "
次日前缀 = "⚠️ "
"""紧急程度图标：当天 🔥、次日 ⚠️、更远什么都不带。"""


def 组头(偏移: int, 侧: str) -> str:
    """偏移 + 侧 → 分组那一行：`🔥 今天结束` / `⚠️ 明天结束` / `3 天后结束`。

    偏移就是"边界距今的天数"（0 = 今天、-1 = 明天、-3 = 三天后）；正数兜底成"N 天前"。
    """
    名字 = "结束" if 侧 == "结束" else "开启"
    if 偏移 == 0:
        return f"{当天前缀}今天{名字}"
    if 偏移 == -1:
        return f"{次日前缀}明天{名字}"
    return f"{-偏移} 天后{名字}" if 偏移 < 0 else f"{偏移} 天前{名字}"


def 条目行(名称: str, 类型: int) -> str:
    """一条活动 → 一行：`📅 活动名`。"""
    return f"{类型图标.get(类型, 缺省图标)} {名称}"


def 省略行(条数: int) -> str:
    """命中太多、被行数上限截掉时的最后一行。"""
    return f"…另有 {条数} 项"


# ============================ 活动名的展示规范 ============================

卡池前缀 = ("【标准池】", "【中坚池】", "【寻访】", "【限时】", "【中坚】", "【标准】")
"""数据层给卡池拼的前缀。展示时整段丢掉——类型已经由甘特图左列表达（`活动.子类型`）。"""

期号_RE = re.compile(r"^#\d+\s*·\s*")
甄选期号_RE = re.compile(r"^(?:定向|中坚|标准)甄选\d*\s*·\s*")
"""卡池名里的期号（`#193 · `、`中坚甄选07 · `）。期号对"这周有什么"没有信息量，一起丢掉。"""

长期别名 = {"【肉鸽】": "【集成战略】"}
"""长期玩法的**历史展示名** → 官方名：「肉鸽」是黑话，PRTS 的 SMW 里没有这个词，只能硬写。"""
长期别名 |= {f"【{写法}】": f"【{官方}】" for 写法, 官方 in 长期活动.官方名.items()
             if 写法 != 官方}
"""其余从 `长期活动.官方名` 派生：旧 CSV 里写着 `【剿灭】` 的，显示成 `【剿灭作战】`。

（这样旧数据不必等重抓就能看到统一写法，与卡池的 `_反推子类型` 同一个思路——区别是
这条没有时效：`展示名` 对任何来源的名字都生效。）"""

附属后缀 = ("关卡", "礼包", "组合包", "时装")
"""活动的附属条目用 `空格 + 后缀` 命名，统一改写成 `· 后缀`（同卡池的 `· 干员`）。"""


def 展示名(名称: str) -> str:
    """图上显示的名字（**只影响显示，不改数据**）。

    数据层的名字来自三个地方、写法本来就不齐：

    - 卡池 —— `解析_卡池.分区规则` 拼出 `【标准池】#193 · 乌尔比安 / 仇白`；
    - 长期 —— `解析_公告.长期任务名` 拼 `【剿灭】默祷圣祠`、`解析_API活动` 拼 `【集成战略】…`；
    - 活动 / 福利 —— 直接用 PRTS 活动页名（PRTS 那边就是这样，不带前缀）。

    统一规则（2026-09-24 定）：

    1. **卡池**：前缀与期号全丢掉（`【标准池】#193 · 乌尔比安 / 仇白` → `乌尔比安 / 仇白`）——
       池子的细分（限时 / 中坚 / 标准 / 甄选）进了甘特图左列，名字只留"谁 UP"或池名；
    2. **附属条目**：`空格 + 后缀` 改成 `· 后缀`，与卡池的 `· 干员` 用同一个分隔符；
    3. **长期**：黑话改官方名（`【肉鸽】` → `【集成战略】`）——左列不细分长期，前缀得留着；
    4. **活动 / 福利**：不加前缀，它们本身就没有细分。
    """
    名 = 名称.strip()
    for 旧 in 卡池前缀:
        if 名.startswith(旧):
            名 = 名[len(旧):]
            break
    名 = 期号_RE.sub("", 名)
    名 = 甄选期号_RE.sub("", 名)
    for 旧, 新 in 长期别名.items():
        if 名.startswith(旧):
            名 = 新 + 名[len(旧):]
            break
    for 尾 in 附属后缀:
        if 名.endswith(" " + 尾):
            return 名[: -len(尾) - 1] + " · " + 尾
    return 名


def 提醒名(名称: str, 子类型: str = "") -> str:
    """提醒里用的名字：**带类型**。

    推送与控制台没有甘特图左列，裸名会丢掉"这是哪个池子"——所以把 `活动.子类型`
    补回前缀。长期/活动/福利的名字里本来就带着类型（`【集成战略】…`），不再补。
    """
    名 = 展示名(名称)
    if 子类型 and not 名.startswith("【"):
        return f"【{子类型}】{名}"
    return 名
