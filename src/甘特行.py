"""甘特图的"行怎么排" —— 纯函数，不依赖 matplotlib（便于直测）。

只有一条规则（2026-09-24 定）：**铺满整幅图的常驻条并成一行**。

为什么并：剿灭作战 / 生息演算 / 集成战略这类常驻玩法的时间窗几乎总盖过整个显示范围，
各自占一行就是几条长得一模一样的长条（除了颜色看不出区别）；并成一行后按数量斜切等分，
一眼能数出"现在有几个常驻玩法"。

某条一旦不再铺满（右端落进窗口），说明它**快结束了**——那时不再并，单独一行把真实排期
画出来。这就是"快要结束"的判据：不猜天数，图上看得见才算。
"""

from __future__ import annotations

from datetime import datetime


def 铺满全图(条目, 左边界: datetime, 右边界: datetime) -> bool:
    """这条的时间窗盖住了整个显示范围 —— 它在图上没有两端，属于"常驻"。"""
    return 条目.开始 <= 左边界 and 条目.结束 >= 右边界


def 分行(显示: list, 左边界: datetime, 右边界: datetime) -> list[list]:
    """行 = 若干条目：相邻且都铺满全图的条目并成一行，其余各自一行。

    入参 `显示` 是渲染顺序（调用方已 `reversed`）；返回值顺序就是自上而下的行顺序。
    """
    行们: list[list] = []
    缓冲: list = []

    def 收() -> None:
        nonlocal 缓冲
        if 缓冲:
            行们.append(缓冲)
            缓冲 = []

    for 条目 in 显示:
        if 铺满全图(条目, 左边界, 右边界):
            缓冲.append(条目)
            continue
        收()
        行们.append([条目])
    收()
    return 行们
