"""甘特图的"行怎么排" —— 纯函数，不依赖 matplotlib（便于直测）。

只有两条规则：

1. **铺满整幅图的常驻条并成一行**（2026-09-24 定）。剿灭作战 / 生息演算 / 集成战略这类
   常驻玩法的时间窗几乎总盖过整个显示范围，各自占一行就是几条长得一模一样的长条
   （除了颜色看不出区别）；并成一行后按数量斜切切分，一眼能数出"现在有几个常驻玩法"。
   某条一旦不再铺满（右端落进窗口），说明它**快结束了**——那时不再并，单独一行把真实排期
   画出来。这就是"快要结束"的判据：不猜天数，图上看得见才算。
2. **同一活动的多时段并成一行**（2026-10-30 定）。SideStory 的一/二/三阶段与商店、
   特别招募的预选/招募，在数据里是**同一活动关联**下的多条记录；各占一行会把同一个活动名
   重复好几遍、也看不出它们属于同一个活动。这里按 `活动关联` 分成一组，交给绘图层
   画成一个"整体条 + 分段"的行。分组只认显式关联，**不从名称或日期猜**。
"""

from __future__ import annotations

from datetime import datetime

复合角色 = frozenset({'关卡开放', '流程阶段', '兑换开放'})
"""参与"多时段并成一行"的业务角色；其余角色（如活动总窗）仍按普通行处理。"""


def 铺满全图(条目, 左边界: datetime, 右边界: datetime) -> bool:
    """这条的时间窗盖住了整个显示范围 —— 它在图上没有两端，属于"常驻"。"""
    return 条目.开始 <= 左边界 and 条目.结束 >= 右边界


def 多时段组(条目们) -> dict[str, list]:
    """同一活动关联、同一活动本名的多时段记录 → {关联键: [条目, …]}。

    只收 `复合角色` 内的记录；同组至少两条、本名一致才算一组。没有显式关联的
    （旧数据、长期活动）不进这里，一律走原来的逐条/常驻逻辑。
    """
    组: dict[str, list] = {}
    for 条目 in 条目们:
        关联 = getattr(条目, '活动关联', '')
        if 关联 and getattr(条目, '时间角色', '') in 复合角色:
            组.setdefault(关联, []).append(条目)
    return {k: v for k, v in 组.items()
            if len(v) > 1 and len({getattr(t, '活动本名', '') for t in v}) == 1}


def 是多时段行(行: list) -> bool:
    """这一行是否是"同一活动的多时段"（绘图层据此换画法、换行高）。"""
    if len(行) < 2:
        return False
    关联 = getattr(行[0], '活动关联', '')
    return bool(关联) and all(getattr(t, '活动关联', '') == 关联 for t in 行)


def 分行(显示: list, 左边界: datetime, 右边界: datetime) -> list[list]:
    """行 = 若干条目：多时段组各占一行，相邻且都铺满全图的条目并成一行，其余各自一行。

    入参 `显示` 是渲染顺序（调用方已 `reversed`）；返回值顺序就是自上而下的行顺序。
    """
    组们 = 多时段组(显示)
    行们: list[list] = []
    缓冲: list = []
    已收: set[str] = set()

    def 收() -> None:
        nonlocal 缓冲
        if 缓冲:
            行们.append(缓冲)
            缓冲 = []

    for 条目 in 显示:
        关联 = getattr(条目, '活动关联', '')
        if 关联 and 关联 in 组们:
            收()
            if 关联 not in 已收:
                行们.append(list(组们[关联]))
                已收.add(关联)
            continue
        if 铺满全图(条目, 左边界, 右边界):
            缓冲.append(条目)
            continue
        收()
        行们.append([条目])
    收()
    return 行们


__all__ = ['复合角色', '铺满全图', '多时段组', '是多时段行', '分行']
